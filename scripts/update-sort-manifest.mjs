import fs from "node:fs";
import crypto from "node:crypto";
import { transformWithEsbuild } from "vite";
import vm from "node:vm";
const root = "public/explanations/ipa-2026-a-2/";
// The isolated host shares the application's authoritative palette via a copy.
fs.copyFileSync("src/ui/tokens.css", root + "theme.css");
// Standalone viewing uses the same overlay implementation as the app host.
fs.copyFileSync("src/ui/scrollbars.css", root + "scrollbars.css");
const scrollbars = await transformWithEsbuild(fs.readFileSync("src/ui/scrollbars.ts", "utf8"), "scrollbars.ts", {
  loader: "ts", target: "es2022", format: "iife", globalName: "OpenCBTSortScrollbars", minify: true,
});
fs.writeFileSync(root + "scrollbars.js", "/* Shared overlay scrollbars. MIT: repository LICENSE. Generated by scripts/update-sort-manifest.mjs. */\n" + scrollbars.code);
const files = ["index.html", "theme.css", "style.css", "scrollbars.css", "sort-engine.js", "lesson.js", "scrollbars.js", "main.js"];
// Only the managed lesson definitions are evaluated at authoring time. The app
// indexes these plain strings and never executes a package to inspect its text.
const lesson = vm.createContext({});
vm.runInContext(fs.readFileSync(root + "lesson.js", "utf8"), lesson, { timeout: 1000 });
const staticText = fs.readFileSync(root + "index.html", "utf8")
  .replace(/<head\b[^>]*>[\s\S]*?<\/head\s*>|<!--[\s\S]*?-->|<(script|style)\b[^>]*>[\s\S]*?<\/\1\s*>/gi, " ")
  .replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim();
const search = {
  summary: "7種類のソートの比較・交換・移動を、同じ数列で再生しながら学べる動作シミュレーターです。",
  keywords: ["ソート", "整列", "アルゴリズム", "計算量", "ピボット", "最大ヒープ", "併合", ...Object.values(lesson.SortLesson.algorithms).flatMap(info => [info.name, info.english])],
  text: Object.values(lesson.SortLesson.algorithms).map(info => Object.values(info).join("\n")).join("\n\n") + "\n\n" + staticText,
};
const manifest = {
  apiVersion: 1, revision: 1, title: "ソートアルゴリズム解説・動作シミュレーター",
  search,
  attribution: {
    origin: "original",
    sourceRefs: [],
    rightsRefs: ["rights-original"], creatorIds: ["codex"],
  },
  references: {
    title: "参考資料（定義・計算量の確認）",
    sourceRefs: ["quick", "bubble", "selection", "insertion", "merge", "heap", "shell", "binary-search-tree", "heap-structure"].map(name => ({ sourceId: `source-nist-sort-${name}`, locator: { section: "Definition / Note" } })),
  },
  files: files.map(file => ({ path: file, mediaType: file.endsWith("html") ? "text/html" : file.endsWith("css") ? "text/css" : "text/javascript", sha256: crypto.createHash("sha256").update(fs.readFileSync(root + file)).digest("hex") })),
};
fs.writeFileSync(root + "manifest.json", JSON.stringify(manifest, null, 2) + "\n");
console.log("Sort explanation manifest updated (8 files, revision 1, shared theme and scrollbars).");
