const keys = 'アイウエ';
function finite(number: number, title: string, name: string, count: number, notes: string,
  build: (input: number) => GeneratedBody, fixed = false): GenerationDefinition {
  return {
    source: '2014h26a-fe-am-' + number, title, fields: [field(name, 0, count - 1)], reference: [0],
    sourceAnswer: source[number].key, version: '3.7.0', notes: variableNotes + ' ' + notes,
    ...(fixed ? { answerVariation: 'fixed' as const } : {}),
    build(values) {
      const [input] = values;
      if (values.length !== 1 || !Number.isSafeInteger(input) || input < 0 || input >= count) throw Error('PARAMETER_CONSTRAINT');
      return build(input);
    },
  };
}

type Scenario = { prompt: string; correct: number; explanation: string; choices?: string[]; extra?: string[] };
function knowledge(number: number, title: string, fieldName: string, notes: string, explanation: string, alternates: Scenario[]) {
  const original = source[number], correct = keys.indexOf(original.key);
  const scenarios: Scenario[] = [{ prompt: original.prompt, correct, explanation }, ...alternates];
  return finite(number, title, fieldName, scenarios.length, notes, input => {
    const scenario = scenarios[input];
    return {
      prompt: [p(scenario.prompt), ...(scenario.extra ?? original.extra).map(p)],
      choices: strings(scenario.choices ?? original.choices), correctIndex: scenario.correct,
      explanation: scenario.explanation,
    };
  }, alternates.every(scenario => scenario.correct === correct));
}
