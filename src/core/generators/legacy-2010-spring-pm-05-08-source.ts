function textOf(block:Block):string{
  if(block.type==='paragraph'||block.type==='code')return block.text;
  if(block.type==='table')return [block.caption,...[block.columns,...block.rows].map(row=>row.join('｜'))].join('\n');
  if(block.type==='diagram')return block.caption+'\n'+block.alt;
  throw new Error('未対応の原資料ブロック');
}
