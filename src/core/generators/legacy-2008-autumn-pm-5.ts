function musicCase(index: number) {
  const data = musicCases[index];
  const optionsF = ['会員番号', '楽曲データの大きさ', '楽曲番号', data.field, 'ダウンロード件数'];
  return { ...data, optionsF, title: data.field + '別ダウンロード件数表' };
}

