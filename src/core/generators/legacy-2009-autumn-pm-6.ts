export function incidentPages(index: number): readonly Page[] {
  const c = scenarios[index];
  const columns = ['項番','改善勧告','改善内容（概要）'];
  const alert = '障害発生時の通報とフォローについて，体制とプロセスを見直すこと。';
  const follow = '問題の解決を確認するプロセスを整備すること。';
  const improve = 'DBの項目を見直し，不足項目を追加すること。また，DBの有効活用を図ること。';
  return [[26, [
    p('問6　インシデント及び問題の管理に関する次の記述を読んで，設問に答えよ。'),
    p(c.business+'の'+c.firm+'では，システム部が'+c.system+'を運用している。このシステムは，'+c.firm+'とその'+c.users+'が利用している。'),
    p('ある日，'+c.start+c.system+'が使えないという状況が発生した。これを知った'+c.users+'の社員が'+c.firm+
      'の担当窓口に問い合わせたところ，'+c.system+'で'+c.problem+'が発生しており，それが'+c.users+'に通報されていないことが分かった。'),
    p('サービスの回復後にシステム部で通報ミスの原因を調べたところ，障害時の連絡先一覧表が古く，連絡先には'+c.users+
      'が含まれていないことが分かった。システム部では，インシデント管理及び問題管理のプロセスが有効に機能しなかったことを反省し，リスク管理部の監査担当者の協力を得て，プロセス全体の見直しを実施した。'),
    p('監査担当者は，見直しで発見された管理上の問題点とそれらに対する改善勧告を表1のようにまとめて，システム部長に報告した。'),
    p('なお，'+c.firm+'ではインシデントの発生から問題の分析・解決までを，障害管理データベース（以下，DBという）で管理している。DBの項目は，次のとおりである。'),
    list(['① 障害管理番号（連番）','② 障害の発生日時','③ システム名','④ コンポーネント名','⑤ 障害の状況（文章で記述）',
      '⑥ 解決の方法（文章で記述）','⑦ 解決担当者名','⑧ 解決日時']),
    table('表1　見直しで発見された管理上の問題点とそれらに対する改善勧告',['項番','管理上の問題点','改善勧告'],[
      ['1','障害発生時の関係部門への通報プロセスが有効に機能していない。',alert],
      ['2','DB中に，インシデント対応は完了しているが，問題の解決が完了していないことを示す，解決日時が空欄のものが多数ある。',follow],
      ['3','DBの現在の項目では不足がある。また，DBが十分に活用されていない。',improve],
      ['⋮','⋮','⋮'],
    ]),
    p('管理上の問題点は多数あったが，システム部では，重要と判断した項番1～3について早急に改善することにした。'),
  ]],[27, [
    p('設問　次の記述中の空欄［a］～［f］に入れる正しい答えを，解答群の中から選べ。'),
    p('(1) 通報とフォローのプロセスについては，表2の内容で改善することにした。'),
    table('表2　通報とフォローのプロセスの改善内容', columns, [[
      '1',alert,c.role+'が［a］を判断。\n・レベル3以上：役員と'+c.users+'に通報し，'+c.summary+
      'に利用者向け状況を掲載。（発生時，発生後'+c.delay+'ごと）\n・レベル2：システム部長が通報先を判断して通報。（発生時，発生後適時）\n・レベル1：システム部外への通報はしない。',
    ]]),
    p('DBに二つの項目を追加する。まず，障害時に最初に判断すべき項目として，項目［a］を設け，そのレベルを事前に定義しておく。障害発生時は，そのレベルに応じた通報を行う。また，項目［b］を設け，これまで重大障害時にホワイトボードなどに記録していた対応状況や回復状況の内容をDBに記録し，システム部員が状況を共有できるようにする。'),
    p('(2) 解決日時が空欄の問題があることについては，表3の内容で改善することにした。'),
    table('表3　解決日時が空欄の問題があることの改善内容',columns,[[
      '2',follow,'① '+c.review+'の問題管理委員会で'+(index===0?'その週':'その対象期間')+'に解決予定の問題の解決状況を確認。\n② 長い間未解決のままの問題は'+c.periodic+'その処置を検討。',
    ]]),
    p('解決日時が空欄の問題を調査したところ，実際に未解決のものと解決日時の登録漏れとが混在していた。そこで，DBに項目［c］を設け，これを基準に問題の解決状況を問題管理委員会で'+c.review+'フォローする。問題管理委員会は実務担当者で構成し，決定事項をシステム部長に後日報告する。'),
    p('なお，未解決の問題のうち，長期間残ってしまう［d］などは，'+c.periodic+'問題管理委員会で終了扱いとするかどうかを決定する。'),
  ]],[28, [
    p('また，解決日時の登録漏れの原因として，次のことが分かった。すなわち，解決方針が決まった問題は，問題管理を離れて，その解決のための作業を［e］のプロセスとして実施している。そのため，DB中の解決日時の更新を，つい忘れてしまう。そこで，問題の解決作業の場合は，該当する障害管理番号を［e］に引き継いで双方の管理が連動するよう，手続を変更する。'),
    p('(3) DBの項目と使いやすさについては，表4の内容で改善することにした。'),
    table('表4　DBの項目と使いやすさの改善内容',columns,[['3',improve,'① 今回は項番1，2の対応で設けた項目だけを追加。\n② システム管理者向けにDBの表示順序を変更。']]),
    p('不足項目について，今回は項番1，2の対応に必要な項目の追加にとどめる。'),
    p('次に，現在のDBの内容の表示順序は，障害管理番号の降順で，重要な問題を見分けにくい。そこで，今回追加する項目を含めて表示の順序を見直し，システム管理者向けに，未解決の問題を重要なものから順に表示するため，［f］が空欄の問題を［a］の降順に並べて表示する機能を追加する。'),
    bankAt(0,'a～c，fに関する解答群'), bankAt(1,'dに関する解答群'), bankAt(2,'eに関する解答群'),
  ]]];
}

export const incidentDefinition = common(6,'インシデント管理と問題管理の改善','障害の対象・連絡体制・監視間隔',
  '公式p26–28。架空企業の監査の改善表1～4、DB8項目、a～fと共有解答群、3レベルと未解決の追跡を保持する。',
  '障害が起きた業務、利用者、通知先と通知・フォローの間隔を変更しました。', values => {
    const index = indexOfCase(values), c = scenarios[index];
    return {
      prompt: readPrompt(incidentPages(index)),
      ...pairedAnswers(incidentBanks(index),[0,0,0,1,2,0],[4,3,2,0,3,0]),
      explanation: [
        'a：'+c.priority+'によって通報先や頻度を決める。b：発生後の対応・回復を時系列で追記し，担当間で共有する。',
        'c：'+c.review+'の会議では，解決予定日時が対象期間にある問題の実績を確かめる。解決日時は完了時点で記録する項目である。',
        'd：原因を特定できず再発しない問題は，観察を経た上で委員会が終了扱いを判断する。業務への影響の小ささや現在の人員・予算だけで終了とはしない。',
        'e：解決方針を決めた後，システムを変更して解決する作業を変更管理へ引き継ぐ。障害管理番号で双方の履歴を対応付ける。',
        'f：解決日時が空欄の問題を選び，重要な問題が先になるようaの降順にする。登録漏れは委員会での突合せで解消する。',
      ].join('\n'),
    };
  });
