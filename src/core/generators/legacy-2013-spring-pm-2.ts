function countFaults(trace: readonly number[], capacity: number) {
  const queue: number[] = [];
  let faults = 0;
  for (const page of trace) {
    if (queue.includes(page)) continue;
    faults++;
    if (queue.length === capacity) queue.shift();
    queue.push(page);
  }
  return faults;
}

