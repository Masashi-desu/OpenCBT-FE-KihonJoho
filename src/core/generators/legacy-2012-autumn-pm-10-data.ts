export function sortedClubProgram(minutes: number) {
  return [
    'MKTIME-PROC.',
    '    PERFORM UNTIL TIME-EOF',
    '       READ TIME-F',
    '          AT END     SET TIME-EOF TO TRUE',
    '          NOT AT END PERFORM MKWORK-PROC',
    '       END-READ',
    '    END-PERFORM.',
    'MKWORK-PROC.',
    '    MOVE T-NO TO W-NO.',
    '    MOVE T-MIN TO W-MIN.',
    '    [e].',
    'MKBILL-PROC.',
    '    PERFORM UNTIL WORK-EOF',
    '       RETURN WORK-F',
    '          AT END     SET WORK-EOF TO TRUE',
    '                     PERFORM WRBILL-PROC',
    '          NOT AT END IF TMP-NO = W-NO OR ZERO THEN',
    '                        [f]',
    '                     ELSE',
    '                        PERFORM WRBILL-PROC',
    '                        MOVE W-MIN TO TMP-MIN',
    '                     END-IF',
    '                     MOVE W-NO TO TMP-NO',
    '       END-RETURN',
    '    END-PERFORM.',
    'WRBILL-PROC.',
    '    PERFORM TEST AFTER',
    '       UNTIL (M-NO = TMP-NO AND NOT WORK-EOF) OR MEM-EOF',
    '       READ MEM-F',
    '          AT END',
    '             SET MEM-EOF TO TRUE',
    '          NOT AT END',
    '             MOVE M-NO TO B-NO',
    '             MOVE BASE-PRICE(M-CODE) TO B-CHG',
    '             IF [g] THEN',
    '                COMPUTE EXT-H = (TMP-MIN - ' + minutes + ' + 59) / 60',
    '                [d]',
    '             END-IF',
    '             WRITE B-REC',
    '       END-READ',
    '    END-PERFORM.',
  ].join('\n');
}
