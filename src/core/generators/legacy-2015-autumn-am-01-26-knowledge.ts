function scenarios(number: number, label: string, originalExplanation: string, variants: readonly Case[],
  notes: string): GenerationDefinition {
  const original = originals[number];
  const all: readonly Case[] = [
    [original.stem, original.choices, 'アイウエ'.indexOf(original.answer), originalExplanation],
    ...variants,
  ];
  return {
    source: `2015h27a-fe-am-${number}`, title: original.title, sourceAnswer: original.answer, version: '3.2.0',
    fields: [field(label, 0, all.length - 1)], reference: [0], notes: variableNotes + ' ' + notes,
    build(values) {
      const index = values[0];
      if (values.length !== 1 || !Number.isSafeInteger(index) || index < 0 || index >= all.length)
        throw new Error('PARAMETER_CONSTRAINT');
      const [stem, choices, correctIndex, explanation] = all[index];
      return { prompt: [p(stem)], choices: strings([...choices]), correctIndex, explanation };
    },
  };
}

function roles(number: number, label: string, variants: readonly (readonly [stem: string, correctIndex: number])[],
  originalExplanation: string, notes: string, variantChoices = originals[number].choices): GenerationDefinition {
  return scenarios(number, label, originalExplanation,
    variants.map(([stem, correctIndex]) => [stem, variantChoices, correctIndex, originalExplanation]), notes);
}

