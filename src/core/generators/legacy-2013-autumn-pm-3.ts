import { p, strings } from './definition';
import { answers, bank, define, single, table } from './legacy-2013-autumn-pm-01-04-shared';
import { ipv6Cases } from './legacy-2013-autumn-pm-01-04-models';

function data(i: number) {
  const c = ipv6Cases[i];
  const quotient = 2 ** 128 / (c.population * 1e8);
  const accurate = (quotient / 1e28).toFixed(1);
  const mistaken = (100 / c.population).toFixed(1);
  const a = [27, 28, 29].map(exponent => accurate + '×10^' + exponent)
    .concat([117, 118, 119].map(exponent => mistaken + '×10^' + exponent));
  const b = [32, 40, 48, 56, 64, 72, 80, 88, 96].map(String);
  const bytes = c.v4.map(byte => byte.toString(16).padStart(2, '0'));
  const [w, x] = [bytes[0] + bytes[1], bytes[2] + bytes[3]];
  const separate = bytes.map(byte => Number.parseInt(byte, 16).toString(16)).join(':');
  const address = c.v4.join(':');
  const prefix = '2002:' + w + ':' + x + '::';
  const candidateC = ['2002::' + w + ':' + x, '2002:0:0:' + w + ':' + x + '::', '2002:' + address + '::',
    '2002:' + separate + '::', prefix, address + '::', w + ':' + x + '::'];
  const [d1, d2] = c.d;
  const dLong = d1.padStart(4, '0') + ':' + d2.padStart(4, '0');
  const start = '2001:0db8:';
  const candidateD = [
    start + '0000:0000:0000:0000:0000:00' + d1 + d2,
    start + '0000:0000:0000:0000:0000:' + d1 + ':0' + d2,
    start + '0000:0000:0000:0000:' + dLong,
    start + '0000:0000:0000:' + dLong,
    start + '0000:0000:' + dLong,
    start + '0000:0000:' + dLong + ':0000',
    start + '0000:0000:' + dLong + ':0000:0000',
  ];
  const e = c.e;
  const candidateE = [
    '2001:0db8::' + e + '::', '2001:0db8::' + e + ':0:0:0', '2001:0db8:0:0:' + e, '2001:0db8:0:0:' + e + '::',
    '2001:db8::' + e + '::', '2001:db8::' + e + ':0:0:0', '2001:db8:0:0:' + e, '2001:db8:0:0:' + e + '::',
  ];
  const f = c.f;
  const candidateF = ['::0:' + f, '::000' + f, '::' + f, ':0::' + f, '0::' + f, '0:0::' + f, '0000::' + f];
  const rows = [
    ['［d］', '2001:db8::' + d1 + ':' + d2], ['2001:0db8:0000:0000:' + e + ':0000:0000:0000', '［e］'],
    ['0000:0000:0000:0000:0000:0000:0000:000' + f, '［f］'],
  ];
  return { banks: [a, b, candidateC, candidateD, candidateE, candidateF], rows, accurate, prefix, bytes };
}

export function autumn2013Pm3Pages(i: number) {
  const c = ipv6Cases[i], { banks, rows } = data(i);
  return [
    [
      p('問3　インターネットプロトコルのアドレス表記に関する記述を読んで，設問1，2に答えよ。'),
      p('インターネットプロトコル（IP）として現時点で広く使われているのは，IPバージョン4（以下，IPv4という）である。IPv4では，そのアドレスを表現するのに32ビットを使用している。単純に32ビットのアドレス空間を考えると，2^32個（約43億個）のアドレスが使用できるが，世界の人口が約' +
        c.population + '億人であるので一人ひとりに1個ずつのアドレスを割り当てられない。今日，インターネットに接続できる機器の数が爆発的に増えていることを考えると，IPv4のアドレスを全て使い切ってしまうのは時間の問題である。これは，“IPv4アドレスの枯渇問題”として知られている。'),
      p('そこで，IPバージョン6（以下，IPv6という）が開発された。IPv6では，アドレスを128ビットで表す。単純に128ビットのアドレス空間を考えると，2^128個（約3.4×10^38個）のアドレスが使用でき，世界中の人に割り当てても一人当たり約［a］個使える計算になる。'),
      p('IPv4では，32ビットのアドレスを表現するのに8ビットごとに区切り，各8ビットの値を10進数で表し，区切りにドット（.）を使用する表記方法が用いられている。IPv6では，128ビットを16ビットごとに区切り，各16ビット（以下，16ビットセクションという）を16進数で表し，区切りにコロン（:）を使用する。また，次の規則を使用してアドレスを表現する文字列を圧縮できる。'),
      p('（1）各16ビットセクションの先行する0を省略する。例えば，0012は12になる。ただし，16ビットセクションが0000のときは，0とする。\n（2）0の16ビットセクションが連続する場合は，連続する2個のコロン（::）で表す。例えば，2001:0db8:0000:0000:0000:ff00:0042:8329は2001:db8::ff00:42:8329と表す。ただし，::は1か所にだけ使用できる。'),
      p('IPv6もIPv4と同様に，アドレスはネットワークを表す部分とホストを表す部分から成る。IPv6では，ネットワークの部分が何ビットで表されるかを示すのにプレフィックス長が用いられる。プレフィックス長は，先頭からのビット数を10進数で表したものである。アドレスとプレフィックス長は，スラッシュ（/）で区切る。例えば，2001:db8:abcd:12::/64では，プレフィックス長は64であり，先頭から64ビットがネットワークアドレス部であることを表している。'),
    ],
    [
      p('IPv6を導入することによってIPv4アドレスの枯渇問題は回避できるが，インターネットにつながる世界中のシステムや機器が一斉にIPv6に変更されるということは期待できず，長い時間を掛けて移行が行われると考えられる。そこで，IPv4からIPv6への移行期間中に二つのバージョンが共存する手段として様々な技術が開発されている。そのうちの一つがトンネル方式であり，送信元と宛先の間に異なるIPバージョンが存在するとき，元のIPバージョンのパケットを異なるIPバージョンのパケットにカプセル化し，異なるIPバージョンのネットワークを通過させる方式である。トンネル方式を実現する方法は幾つかあり，6to4と呼ばれる技術もその一つである。'),
      p('6to4では，IPv4のグローバルアドレスが必要である。6to4で使用するIPv6アドレスの最初の16ビットは，必ず2002である。続いてIPv4のグローバルアドレスをそのまま付けた［b］ビットがIPv6アドレスのプレフィックスとなる。例えば，' +
        (i === 0 ? 'IPv4グローバルアドレスが' + c.v4.join('.') + 'の場合' : 'IPv4アドレスの表記例として' + c.v4.join('.') + 'を当てはめた場合') +
        '，IPv6アドレスのプレフィックスは，［c］/［b］となる。'),
    ],
    [
      p('設問1　説明文中の空欄に入れる正しい答えを，解答群の中から選べ。'),
      ...bank('aに関する解答群', banks[0]), ...bank('bに関する解答群', banks[1]), ...bank('cに関する解答群', banks[2]),
    ],
    [
      p('設問2　表1は，IPv6アドレスの基本形と，それを最も短く表現する圧縮形の対応を示したものである。表1中の空欄に入れる正しい答えを，解答群の中から選べ。ここで，基本形は全16ビットセクションを4桁の16進数で表現したもの（先行する0を省略しない）である。'),
      table('表1　IPv6アドレスの基本形と圧縮形の対応', ['基本形', '圧縮形'], rows),
      ...bank('dに関する解答群', banks[3]), ...bank('eに関する解答群', banks[4]), ...bank('fに関する解答群', banks[5]),
    ],
  ];
}

