import type { PartAnswer } from '../types';
import { p, strings, table } from './definition';
import { answers, bank, define, single } from './legacy-2005-autumn-pm-01-05-shared';
import { draw } from './legacy-2005-autumn-pm-01-05-figures';
import { hrCases } from './legacy-2005-autumn-pm-01-05-models';

const fileChoices=['S1','S2','S3','昇格者','職務変更'];
const transpositions=[
  '処理6→処理7→処理8→処理5','処理7→処理8→処理5→処理6',
  '処理8→処理5→処理6→処理7','処理8→処理7→処理6→処理5',
];
const processes=Array.from({length:8},(_,i)=>'処理'+(i+1));
const oldTableChoices=[
  '処理5の更新反映前の社員表',
  '処理5の更新反映後，かつ処理6の更新反映前の社員表',
  '処理6の更新反映後，かつ処理7の更新反映前の社員表',
  '処理7の更新反映後，かつ処理8の更新反映前の社員表',
];
const layout=(name:string,i:number)=>draw('hr-layout',i,name);

export function autumn2005Pm5Pages(index:number,print=true) {
  const {monthLabel,previousMonth,prevLast,minimumYears,gradeIncrease}=hrCases[index];
  const date=monthLabel+'1日', cutoff=(minimumYears===1?'前年':minimumYears+'年前')+'の'+date;
  const floor=gradeIncrease===2?'2級又は1級の場合':'1〜'+gradeIncrease+'級の場合';
  const originalRule='会社は，毎年'+date+'に職務変更も昇格もしていない社員の階級を'+gradeIncrease+
    '上げる。これを昇級という。ただし，昇級前の階級が'+floor+'は1級となる。また，入社後'+minimumYears+'年に満たない社員は，昇級の対象から除外する。';
  const updateRankRule='階級更新ファイルから読み込んだレコードの社員コードを用いて，社員表の階級を更新する。社員表を社員コードで検索して取得した階級が'+
    (gradeIncrease===2?'2級':gradeIncrease+'級以下')+'の場合，当該レコードの階級の値を1にする。それ以外の場合は，階級の値を'+gradeIncrease+'だけ引いた値に更新する。';
  return [
    [p('プログラム設計に関する次の記述を読んで，設問1〜4に答えよ。'),
      p('社員が所属する部署，従事する職務や階級などを管理する社員表を，昇級，昇格，職務変更などの人事変更情報を基に更新するシステムを設計する。'),
      p('〔A社の人事規定と人事変更情報〕'),
      p('（1）社員には，入社時に7けたの数字からなる社員コードを割り当てる。社員コードは，社員を一意に特定できる重複しない番号である。'),
      p('（2）すべての社員は，一つの部署だけに所属する。部署名は，部署コードをキーとして部署表に格納されている。部署表のレコード様式を次に示す。下線は，主キーを表す。'),
      layout('部署表のレコード様式',0),
      p('（3）営業，事務，技術などの職務名は，職務コードをキーとして職務表に格納されている。職務表のレコード様式を次に示す。また，すべての社員は一つだけの職務につく。'),
      layout('職務表のレコード様式',1),
      p('（4）すべての社員は，管理職か一般職のいずれかの職群に属する。管理職には1〜20級の階級があり，一般職には1〜30級の階級がある。階級の値が減ることを階級が上がるという。'),
      p('（5）社員の入社年月日，所属する部署，従事する職務などの情報は，社員コードをキーとして社員表に格納されている。社員表のレコード様式を次に示す。'),
      layout('社員表のレコード様式',2)],
    [p('（6）別の職務を希望する社員は，毎年'+previousMonth+'月1日から'+previousMonth+'月15日までに，希望する職務を会社に伝える。この情報は職務変更ファイルに許可フラグの初期値を0として格納される。職務変更ファイルのレコード様式を次に示す。'),
      layout('職務変更ファイルのレコード様式',3),
      p('（7）会社は，社員が希望する別の職務への従事を許可する場合，毎年'+previousMonth+'月'+prevLast+'日までに，職務変更ファイルの許可フラグに1を設定する。その年の'+date+'には，会社が許可した社員の職務を希望した職務に変更する。これを職務変更という。'),
      p('（8）会社は，一般職の社員のうち管理能力に秀でた社員を，管理職に任命する。これを昇格という。昇格候補の社員の情報は，毎年'+previousMonth+'月'+prevLast+
        '日までに昇格候補ファイルに格納される。昇格はその年の'+date+'に行い，当日職務変更していない社員だけが昇格できる。昇格のとき，職群は管理職に，階級は20級になる。昇格候補ファイルのレコード様式を次に示す。'),
      layout('昇格候補ファイルのレコード様式',4),p('（9）'+originalRule),
      p('（10）会社は，毎年'+date+'に，社員に対して所属している部署から別の部署へ異動する人事異動を発令する。人事異動の発表資料の例を図1に示す。異動の対象社員の情報は，前日までに異動ファイルに格納される。異動ファイルのレコード様式を次に示す。'),
      layout('異動ファイルのレコード様式',5)],
    [draw('hr-report',index,'図1　人事異動の発表資料の例'),
      p('（11）図2に社員表の更新に必要なファイル作成の流れ図を，図3に社員表の更新と人事異動の発表資料作成の流れ図を示す。図中の昇格者ファイルは，職群を更新する社員の社員コードだけのレコードからなるファイルである。階級更新ファイルは，階級を更新する社員の社員コードだけのレコードからなるファイルである。')],
    [draw('hr-create',0,'図2　昇格者ファイルと階級更新ファイルの作成の流れ'),
      draw('hr-update',0,'図3　社員表の更新と人事異動の発表資料作成の流れ')],
    [p('表は，図2と図3で使用する処理を分類し，機能概要を一覧にしたものである。'),
      table('表　処理と機能概要の一覧',['処理','分類','機能概要'],[
        ['1','抽出','職務変更ファイルからレコードを読み込み，許可フラグが1のレコードをS1ファイルとして出力する。'],
        ['2','突合せ','［a］ファイルとS3ファイルを読み込み，読み込んだレコードの社員コードを比較し，［a］ファイルにはなくS3ファイルにはある社員コードのレコードを，昇格者ファイルとして出力する。'],
        ['3','抽出','社員表からレコードを読み込み，階級の値が2〜30であって入社年月日が'+cutoff+'以前のレコードを選び，社員コードの昇順に並べ，S4ファイルとして出力する。'],
        ['4','突合せ','［b］ファイルとS4ファイルを読み込み，読み込んだレコードの社員コードを比較し，［b］ファイルにはなくS4ファイルにはある社員コードのレコードを，階級更新ファイルとして出力する。'],
        ['5','更新',updateRankRule],
        ['6','更新','S2ファイルから読み込んだレコードの社員コードと希望職務コードを用いて，社員表の該当レコードの職務コードを更新する。'],
        ['7','更新','昇格者ファイルから読み込んだレコードの社員コードを用いて，社員表の該当レコードの職群を“管理職”に，階級の値を20に更新する。'],
        ['8','更新','異動ファイルから読み込んだレコードの社員コードと異動先部署コードを用いて，社員表の該当レコードの部署コードを更新する。'],
        ['9','作表','異動ファイルから読み込んだレコードの社員コードで社員表を検索し，旧社員表，部署表と職務表を用いて人事異動の発表資料を作成する。'],
      ]),
      p('設問1　処理2では職群を更新する社員コードだけのレコードからなる昇格者ファイルを，処理4では階級を更新する社員コードだけのレコードからなる階級更新ファイルを，それぞれ作成する。図2及び表中の空欄に入れる正しい答えを，解答群の中から選べ。解答は，重複して選んでもよい。'),
      ...(print?bank('解答群',fileChoices):[])],
    [p('設問2　図3の中で，処理5〜8の順番を入れ替え，入替え前と同じ処理結果が得られるように並べたものはどれか。正しい答えを，解答群の中から選べ。'),
      ...(print?bank('解答群',transpositions):[]),
      p('設問3　人事規定の見直しがあり，〔A社の人事規定と人事変更情報〕の（9）が次のとおり変更される（変更部分を波線で示す）。ファイルの項目を変更しない場合，図2と図3の中で，修正が必要な処理はどれか。正しい答えを，解答群の中から二つ選べ。'),
      draw('hr-revised',index,'変更後の昇級規定'),...(print?bank('解答群',processes):[]),
      p('設問4　図3の処理9で用いる社員表には，人事異動の結果が反映されている。人事異動の発表資料を作成するために必要な旧社員表として正しい答えを，解答群の中から選べ。'),
      ...(print?bank('解答群',oldTableChoices):[])],
  ];
}

export const autumn2005Pm5=define(
  5,'人事変更のファイル作成・突合せと更新順序','a=イ／b=イ／設問2=ウ／設問3=ウ・オ／設問4=ア',
  '人事の基準日、勤続年数の閾値、昇級幅と勤続年数の短い社員への取扱い',
  '原資料の人事規定・ファイル処理は維持し、日付・勤続条件・階級更新の幅・発表サンプルを整合して変更する。',
  '7けたの社員コード、主キー、管理職と一般職の階級範囲、個別ファイルの区分、選択肢の順、部署と職務・階級の独立性、昇格・階級更新の優先を保持。a/bは重複可の別欄。設問3の二つは一欄のチェックリスト。',
  index=>{
    const {gradeIncrease,minimumYears,newHireIncrease}=hrCases[index];
    const body=answers([strings(fileChoices),strings(transpositions),strings(processes),strings(oldTableChoices)],[
      single('a','a',0,1),single('b','b',0,1),single('s2','設問2',1,2),
      {ids:['s3-1','s3-2'],labels:['設問3','設問3'],bank:2,correct:[2,4]},
      single('s4','設問4',3,0),
    ]);
    const partAnswers=body.partAnswers!.map((answer):PartAnswer=>answer.kind==='unordered'
      ?{...answer,presentation:'checklist'}:answer);
    return {prompt:autumn2005Pm5Pages(index,false).flat(),...body,partAnswers,
      explanation:'許可済みの職務変更者を社員コード順で保持するS2ファイルを，昇格候補のS3と階級更新候補のS4から差し引く。両方に必要なのはS2。'+
        '処理5と処理7はどちらも階級を更新し得る。昇格者の最終階級を20にするため処理5を先にし，職務と所属部署を更新する処理6・8は別の項目なので順番を移動できる。'+
        '見直し後は勤続'+minimumYears+'年未満の社員を処理3で除外せず，処理5で'+newHireIncrease+'級，該当する勤続年数の社員は'+
        gradeIncrease+'級上げるようにする。変更の前後を両方表示する処理9には，最初の処理5が反映される前の社員表が要る。'};
  },{answerVariation:'fixed'},
);
