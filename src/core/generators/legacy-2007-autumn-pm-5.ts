import { p, strings, table } from './definition';
import { answers, bank, bankBlocks, define, single } from './legacy-2007-autumn-pm-01-05-shared';
import { draw } from './legacy-2007-autumn-pm-01-05-figures';
import { saleCases } from './legacy-2007-autumn-pm-5-model';

const columns = ['中間表 A', '中間表 B'];
const fields = [['会員 ID', '商品カテゴリ'], ['会員 ID', '商品名'], ['商品コード', '商品価格'],
  ['商品コード', '商品カテゴリ'], ['商品コード', '商品名']];
const pairs = fields.map(row => [table('解答群　項目の組合せ', columns, [row])]);
const recordChoices = ['最も新しい購入日時をもつレコード', '最も多い購入数量をもつレコード', '最も大きい購入金額をもつレコード',
  '最も小さい購入金額をもつレコード', '最も古い購入日時をもつレコード'];
const sourceTables = ['購入表', '購入明細表', '商品表'];
const sourceFields = ['会員 ID', '購入番号', '商品コード'];

export function autumn2007Pm5Pages(index: number, print = true) {
  const {maximum, selection, cutoff, order, existing} = saleCases[index];
  const chosen = ['最も新しい購入', '最も古い購入', '購入金額が最も大きい購入', '購入金額が最も小さい購入'][index];
  const selectedTime = ['最も新しい購入日時', '最も古い購入日時', '購入金額が最も大きい取引の購入日時', '購入金額が最も小さい取引の購入日時'][index];
  const extracted = selection + '購入実績の抽出';
  const deleteProducts = (existing ? '未購入商品' : '購入済商品') + 'の削除';
  const pages = [
    [p('プログラム設計に関する次の記述を読んで，設問1〜3に答えよ。'),
      p('Z社は Web を使った通信販売システムによって，会員に商品を販売している。会員は，Z社の提供する通信販売システムを利用して商品を購入する。今回，Z社では，会員ごとの購入実績を用いて，購入の可能性が高いと判定された商品を表示する関連商品表示プログラムを開発した。'),
      p('〔通信販売システムの概要〕'),
      p('（1）通信販売システムは Z 社の会員だけが利用でき，会員は一意の会員 ID をもつ。'),
      p('（2）通信販売対象の商品は商品表に登録されている。商品表のレコード様式を図1に示す。'),
      draw('sale-product', 0, '図1　商品表のレコード様式'),
      p('（3）会員は次の手順で，商品の購入操作を行う。'),
      p('① 通信販売システムに会員 ID とパスワードを入力し，ログインする。'),
      p('② 購入を希望する商品を検索する。'),
      p('③ 購入する商品を指定し，購入数量を入力する。商品価格と購入数量の乗算が行われ，購入金額に加えられる。購入する商品がほかにもある場合は，②に戻る。'),
      p('④ 購入金額を確認し，支払方法を入力する。このときの日時が購入日時として記録される。'),
      p('⑤ ログアウトする。'),
      p('（4）会員が支払方法を入力したとき，商品の購入が成立し，その際に一意な購入番号を割り当てる。購入番号をキーとして，購入日時，会員 ID 及び購入金額を，購入表に登録する。また，会員が購入した商品は，商品ごとに購入番号と商品コードをキー項目として購入明細表に登録する。'),
      p('なお，1回のログインで同一商品を複数回に分けて指定したときには，その商品の購入数量を合計し，1件のレコードとして購入明細表に登録する。購入表と購入明細表のレコード様式を図2に示す。')],
    [draw('sale-details', 0, '図2　購入表と購入明細表のレコード様式'),
      p('〔関連商品表示プログラムの概要〕'),
      p('（1）新規登録商品の表示機能'),
      p('会員がログインしたとき，その会員 ID で' + (index === 0 ? '最近購入した商品' : chosen + 'の商品') +
        'と同一商品カテゴリの商品の情報を，商品表から最大' + maximum + '件表示する機能である。ただし，表示する商品の情報は，その会員の' +
        selectedTime + cutoff + 'に商品表に登録されたものだけとする。' +
        (index ? '対象の' + chosen + 'は，会員ごとに一意とする。' : '')),
      p('① ' + extracted),
      p('ログイン時に入力された会員 ID を用いて，購入表と購入明細表からその会員の' + chosen + 'の実績をすべて取り出す。'),
      p('② 商品カテゴリの抽出'),
      p('①で取り出した購入の実績のレコードと商品表のレコードを，商品コードをキーとして突き合わせ，一致したときに商品表から商品カテゴリを取り出す。'),
      p('③ 登録商品の抽出'),
      p('②で取り出した商品カテゴリのすべてと，商品表の商品カテゴリを突き合わせ，等しい商品カテゴリをもつ商品表のレコードをすべて取り出す。'),
      p('④ 新規登録商品の表示'),
      p('③の結果を基に，その会員の' + selectedTime + cutoff + 'に商品表に登録された商品のうち，登録日時が' + order +
        'ものから最大' + maximum + '件の情報を表示する。'),
      p('（2）検索した商品に関連する商品の表示機能'),
      p('会員がある商品を検索したとき，その商品を既に購入した他会員が同時に購入した商品の情報を，最大' + maximum +
        '件表示する機能である。ただし，表示する商品の情報はその会員が' + (existing ? '既に購入した' : 'まだ購入していない') + '商品だけとする。'),
      p('① 購入番号の抽出'),
      p('検索した商品の商品コードを用いて，購入明細表からその商品コードをもつすべてのレコードの購入番号を取り出す。その購入番号とログイン時に入力された会員 ID を用いて，購入表を検索し，他会員の購入番号だけを取り出す。')],
    [p('② 同時購入商品の抽出'),
      p('①で取り出した他会員の購入番号ごとに購入明細表を検索し，その購入番号をもつレコードをすべて取り出す。'),
      p('③ 検索した商品の削除'),
      p('②で取り出したレコードの商品コードと，会員が検索した商品の商品コードを突き合わせ，検索した商品の商品コードをもつレコードをすべて取り除く。'),
      p('④ 関連商品の抽出'),
      p('③で残ったレコードの商品コードのすべてと商品表のレコードを，商品コードをキーとして突き合わせ，一致したレコードを商品表から取り出す。'),
      p('⑤ ' + deleteProducts),
      p(existing ? '④の結果を基に，その会員が購入したことのない商品を取り除く。' :
        '④の結果を基に，その会員が既に購入した商品の商品コードをもつレコードをすべて取り除く。'),
      p('⑥ 関連商品の表示'),
      p('⑤の結果を基に，登録日時が' + order + 'ものから最大' + maximum + '件の商品の情報を取り出し表示する。')],
    [draw('sale-new', index, '図3　新規登録商品の表示機能'),
      draw('sale-related', index, '図4　検索した商品に関連する商品の表示機能')],
    [p('設問1　図3中の中間表 A 及び中間表 B で保持する項目のうち，“商品カテゴリの抽出”，“登録商品の抽出”で必要とする項目の組合せとして正しい答えを，解答群の中から選べ。')],
    [p('設問3　図4中の“' + deleteProducts + '”に関する次の説明中の空欄に入れる正しい答えを，解答群の中から選べ。'),
      p('中間表 G から読み込んだレコードの商品コードを用いて，［b］を検索し，等しい商品コードをもつ［c］をすべて取り出す。［c］ごとに［d］を検索し，ログインのときに入力した会員 ID をもつレコードが一つでも' +
        (existing ? 'なければ，商品は未購入と判定し，取り除く。' : 'あれば，商品は既に購入済みと判定し，取り除く。'))],
  ];
  if (print) pages[4].push(...bankBlocks('解答群', pairs));
  pages[4].push(p('設問2　図3中の“' + extracted + '”に関する次の説明中の空欄に入れる正しい答えを，解答群の中から選べ。'),
    p('ログイン時に入力された会員 ID を用いて，購入表からその会員の［a］を1件取り出す。取り出したレコードの購入番号をもつレコードを購入明細表からすべて取り出す。取り出した結果を中間表 A のレコード様式に編集し，中間表 A に出力する。購入表に該当するレコードが存在しない場合は，何も出力しない。'));
  if (print) pages[4].push(...bank('解答群', recordChoices));
  if (print) pages[5].push(...bank('b，dに関する解答群', sourceTables), ...bank('cに関する解答群', sourceFields));
  return pages;
}

export const autumn2007Pm5 = define(5, '通販の購入実績を基にした関連商品表示', '設問1=エ／a=ア／b=イ／c=イ／d=ア',
  '購入を選ぶ基準・登録日時・表示上限・購入済みの扱い',
  '購入・購入明細・商品表を突き合わせる処理を追い，必要な項目と取得するレコードを選ぶ。',
  '購入確定、重複購入数量の集計、3レコードとキー、図3・4の入出力依存と4注記、購入なしの非出力、4欄＋組合せ5択を保持。購入基準・登録範囲と順・採否条件・上限を変える。', index => {
    const { selection, existing } = saleCases[index];
    return { prompt: autumn2007Pm5Pages(index, false).flat(),
      ...answers([pairs, strings(recordChoices), strings(sourceTables), strings(sourceFields)],
        [single('s1', '設問1', 0, 3), single('a', '設問2 a', 1, [0, 4, 2, 3][index]),
          single('b', '設問3 b', 2, 1), single('c', '設問3 c', 3, 1), single('d', '設問3 d', 2, 0)]),
      explanation: '中間表 A の商品コードで商品表を検索して商品カテゴリを取り出し，中間表 B に入れる。設問2では対象会員の' + selection +
        '購入を購入表から1件選び，同じ購入番号をもつ明細を読み出す。関連商品のコードで購入明細表を検索し，得た購入番号ごとに購入表を検索する。現在の会員 ID と一致する購入が' +
        (existing ? 'なければ未購入なので取り除く。' : 'あれば購入済みなので取り除く。'),
    };
  });
