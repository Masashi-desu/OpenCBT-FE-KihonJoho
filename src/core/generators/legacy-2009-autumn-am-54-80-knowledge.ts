type Choices = readonly [string, string, string, string];
type Case = { prompt: string; answer: number; explanation: string; choices?: Choices };
type Model = { notes: string; explanation: string; variants: readonly [Case, Case, Case] };

function named(prompt: string, explanation: string, variants: readonly [readonly [string, number, string], readonly [string, number, string], readonly [string, number, string]], notes: string): Model {
  const [first, second, third] = variants;
  const build = ([subject, answer, detail]: readonly [string, number, string]) =>
    ({ prompt: prompt.replace('〔対象〕', subject), answer, explanation: detail });
  return { notes, explanation, variants: [build(first), build(second), build(third)] };
}

