function row(prompt: string, choices: readonly string[], key: number, explanation: string): GeneratedBody {
  return { prompt: [p(prompt)], choices: strings([...choices]), correctIndex: key, explanation };
}

function origin(number: number, explanation: string): GeneratedBody {
  const item = source[number];
  return row(item.prompt, item.choices, 'アイウエ'.indexOf(item.key), explanation);
}

function named(number: number, targets: readonly string[], order: readonly number[], explanations: readonly string[]) {
  return (index: number) => row(source[number].prompt.replace(targets[0], targets[index]), source[number].choices,
    order[index], explanations[index]);
}

