import { p, strings, table } from './definition';
import { answers, bank, define, single } from './legacy-2011-special-pm-01-04-shared';
import { draw } from './legacy-2011-special-pm-01-04-figures';
import { routeColumns, routeSetOptions, routingCase } from './legacy-2011-special-pm-01-04-models';

const routeKey = ['ABCD', 'ABC', 'ABD', 'ACD', 'BCD', 'CD'];
const example = (index: number) => {
  const { subnet, ip } = routingCase(index);
  return [[subnet(0), '―', '0'], [subnet(1), '―', '0'], [subnet(2), ip(1, 1), '1'], [subnet(3), ip(1, 1), '2']];
};

export function special2011Pm4Pages(index: number) {
  const { ip, gap, period, observe, seconds, candidates } = routingCase(index);
  return [[
    p('問4　ルータの経路制御テーブルの更新に関する次の記述を読んで，設問に答えよ。'),
    p('ルータは，二つ以上の異なるネットワークをまたいだ通信における通信経路の選択を，ルータ内の経路制御情報を格納したテーブル（以下，テーブルという）に基づいて行う。同一のネットワークに接続された端末（ルータを含む）は同じネットワークアドレスをもつ。あるネットワークでブロードキャストしたパケットは異なるネットワークには転送されない。'),
    p('テーブルの各レコードは送信先ネットワークのための経路制御情報を表し，送信先ネットワークアドレス（主キー），転送先ルータのIPアドレス及び距離で構成される。送信先ネットワークアドレスは受信したパケットのあて先のネットワークアドレスであり，転送先ルータのIPアドレスはそのパケットを転送すべきルータのIPアドレスである。あるネットワークあてのパケットは，該当する転送先ルータに転送すればよいことを表す。距離は，そのルータから転送されたパケットが，送信先のネットワークに到達するまでに経由する，ルータの個数である。'),
    p('ネットワーク構成の例を図1に，図1中のルータ1のテーブルの例を図2に示す。'),
    draw('networks', index, '図1　ネットワーク構成の例'),
  ], [
    table('図2　ルータ1のテーブルの例', routeColumns, example(index)),
    p('転送先ルータのIPアドレスの“―”は，送信先ネットワークとこのテーブルをもつルータが，直接つながっていることを表す。'),
    p('ルータ1がネットワークCに接続された端末あてのパケットを受信したとき，そのパケットはIPアドレス' + ip(1, 1) +
      'のルータ（ルータ2）に転送すればよいことを表す。'),
    p('ルータは，同一のネットワークに接続しているほかのルータが，ブロードキャストで定期的に送信する経路制御情報を受信することによって，自身のテーブルを更新する。これによって，異なるネットワーク上の端末にパケットを送信するときに，目的の端末にパケットが到達するまでに経由するルータの個数が最小になるよう，テーブルを動的に構成することができる。テーブルの更新手順を次に示す。'),
    p('〔テーブルの更新手順〕'),
    p('（1） ルータは，そのルータに直接接続されたすべてのネットワークに，ブロードキャストで，保持するすべての経路制御情報を送信する。最初の送信は起動直後に行い，以後' + period + '秒間隔で送信する。'),
    p('（2） 起動中のルータは，ほかのルータから送信された経路制御情報を受信し，自身のテーブルを次のとおりに更新する。'),
    p('① 受信した経路制御情報のそれぞれの距離に1を加え，その距離を更新距離とする。'),
    p('② 受信した経路制御情報のうち，送信先ネットワークアドレスが一致するレコードが自身のテーブルにあるものは，更新距離と該当するレコードの距離を比較し，更新距離の方が小さい場合は，距離を更新距離の値に，転送先ルータのIPアドレスを受信した経路制御情報の送信元ルータのIPアドレスに更新する。'),
    p('③ 受信した経路制御情報のうち，送信先ネットワークアドレスが一致するレコードが自身のテーブルにないものは，自身のテーブルに追加する。ただし，距離は更新距離の値とし，転送先ルータのIPアドレスは受信した経路制御情報の送信元ルータのIPアドレスとする。'),
  ], [
    p('設問　次の記述中の［空欄］に入れる正しい答えを，解答群の中から選べ。'),
    p('図1のネットワーク構成の例において，ルータ1，2，3を順に，' + gap +
      '秒間隔で起動した。各ルータの起動直後のテーブルには，それぞれのルータが直接接続されたネットワーク（ルータ1ではネットワークAとネットワークB）の経路制御情報だけがあるとすると，ルータ1にネットワークCのための経路制御情報が反映されるのは，図3に示すように，ルータ1を起動した' +
      gap + '秒後（ルータ2が起動直後に送信したテーブルを受信したとき）であり，ネットワークDのための経路制御情報が反映されるのは，ルータ1の起動から［a］秒後である。'),
    draw('routeUpdate', index, '図3　ネットワークCのための経路制御情報のルータ1への反映'),
  ], [
    p('ルータ2にネットワークAのための経路制御情報が反映されるのは，ルータ1の起動から［b］秒後であり，そのときのルータ2のテーブルは，表1となる。'),
    table('表1　ルータ2のテーブル', [''], [['［c］']]),
    p('また，ルータ1の起動から' + observe[0] + '秒後には，ルータ3のテーブルに，［d］のための経路制御情報が保持され，' +
      observe[1] + '秒後には，［e］のための経路制御情報が保持されている。'),
    ...bank('a，bに関する解答群', seconds),
    p('cに関する解答群'),
    ...candidates.map((rows, i) => table('アイウエ'[i], routeColumns, rows)),
    ...bank('d，eに関する解答群', routeSetOptions),
  ]];
}

export const legacy2011SpecialPm4Definition = define(4, 'ルータの経路制御テーブルの更新',
  'a=エ・b=ウ・c=イ・d=カ・e=ア', 'ネットワークアドレス・起動と送信の間隔・観測時刻',
  'ネットワークのIPアドレス、ルータの起動間隔と送信間隔、経路情報を確認する時刻を変えます。',
  'p.18〜21。4ネットワークと3台のルータ，双方のインタフェースとマスク，起動直後の直接接続，' +
  '定期送信と同一ネットワーク内だけの到達，距離の比較・追加，解答群の表4種の実効アドレスを保持。' +
  '起動間隔と送信間隔の組合せでB到達時にDが含まれる場合と含まれない場合を扱う。', index => {
    const { a, b, c, d, e, seconds, candidates, gap, period, observe } = routingCase(index);
    const routeTableChoices = candidates.map(rows => [table('ルータ2のテーブル', routeColumns, rows)]);
    return {
      prompt: special2011Pm4Pages(index).flat(),
      ...answers([strings(seconds.map(String)), routeTableChoices, strings(routeSetOptions)], [
        single('a', 'a', 0, seconds.indexOf(a)), single('b', 'b', 0, seconds.indexOf(b)),
        single('c', 'c', 1, c), single('d', 'd', 2, routeKey.indexOf(d)), single('e', 'e', 2, routeKey.indexOf(e)),
      ]),
      explanation: '直接つながるネットワークだけが同じブロードキャストを受け取る。ルータ3が' + (2 * gap) +
        '秒に起動してDを送るとルータ2はDを知り，その後のルータ2の送信でルータ1へDが反映されるのは' + a +
        '秒。ルータ2は起動前の0秒の送信を受け取れず，ルータ1の次の送信である' + period +
        '秒に初めてAを知る。その時点でDの情報は' + (c === 0 ? 'まだない' : 'ルータ3から受信済み') +
        'ので，ルータ2のテーブルは' + 'アイウエ'[c] + 'となる。ルータ3は自身のC，Dを起動直後から持ち，' +
        'ルータ2の送信でBとAの情報を得る。' + observe[0] + '秒時点は' + [...d].join('，') + '，' +
        observe[1] + '秒時点は' + [...e].join('，') + 'である。',
    };
  });
