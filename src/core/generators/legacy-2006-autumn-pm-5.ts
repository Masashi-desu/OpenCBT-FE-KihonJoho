import { code, p, strings } from './definition';
import { answers, bank, bankBlocks, define, single } from './legacy-2006-autumn-pm-01-05-shared';
import { draw } from './legacy-2006-autumn-pm-01-05-figures';
import { mixtureLabels } from './legacy-2006-autumn-pm-5-model';

const aOptions=['製造日が変わる','製品コードが変わる','牧場区分が変わる','ロット番号が変わる'];
const lastOptions=['エラー','混合','集計','単一'];

export function autumn2006Pm5Pages(index:number,print=true){
 const {farms:[f1,f2,f3],mix,remainder,farms,vars,first,second,tests,amounts}=mixtureLabels(index);
 const names=[f1,f2,f3].map(f=>f+'牧場');
 const bankLogic=tests.map(text=>[code(text,'pseudocode')]);
 return [
  [p('プログラム設計に関する次の記述を読んで，設問1〜3に答えよ。'),
   p('B社は，バター，チーズ，ヨーグルトなど，牛乳を主な原料とする乳製品を製造している。牛乳は，'+names[0]+'，'+names[1]+'及び'+names[2]+'から仕入れ，個別のタンクに保存されている。'),
   p('製造計画で，ロット番号とよばれるコードで識別される製造単位ごとに，単一の牧場の牛乳を使うか，又は標準の混合割合で混合して使うかを決める。ロット番号は，同一製品の同一製造日の製造単位ごとに付けられるコードである。'),
   p('B社では，製造計画で決められた，製造日ごとの各牧場の牛乳の必要量を集計するプログラムを作成することになった。'),
   p('〔必要量ファイルの説明〕'),p('製造計画で決められた，製造日，製品コード，ロット番号ごとに，原料牛乳の“必要量”（正の整数値）と，単一か混合かを表す“牧場区分”が格納されている。牧場区分は，'+names[0]+'，'+names[1]+'及び'+names[2]+'を表す“'+f1+'”，“'+f2+'”，“'+f3+'”，又は混合を表す“'+mix+'”のどれかである。'),
   p('必要量ファイルの様式を図1に示す。レコードは，“製造日”，“製品コード”，“ロット番号”を，この順で整列キーとして，昇順に整列されている。'),
   draw('needed-file',0,'図1　必要量ファイルの様式'),
   p('〔標準混合割合ファイルの説明〕'),
   p('“製品コード”をキーとする索引ファイルである。製品ごとに各牧場の牛乳の標準混合割合が，合計で100％となるように，百分率（0〜100の整数値）で格納されている。標準混合割合ファイルの様式を図2に示す。'),
   draw('ratio-file',index,'図2　標準混合割合ファイルの様式')],
  [p('〔集計ファイルの説明〕'),p('製造日ごとの各牧場の牛乳の必要量を集計して，総必要量として格納する。集計ファイルの様式を図3に示す。'),
   draw('totals-file',index,'図3　集計ファイルの様式'),
   p('〔プログラムの説明〕'),p('必要量ファイルを読み，レコードごとに，次の処理①〜③のどれかを行う。'),
   p('① 牧場区分が“'+mix+'”のときは，“混合”であり，標準混合割合ファイルと必要量ファイルの情報から，'+names[0]+'，'+names[1]+'及び'+names[2]+'のそれぞれの必要量を計算する。この計算は，小数点以下切捨てとし，切捨て誤差は，'+names[remainder]+'の牛乳の必要量で補正する。'),
   p('② 牧場区分が“'+f1+'”，“'+f2+'”及び“'+f3+'”のときは，“単一”であり，必要量の全量を，“'+f1+'”のときは'+names[0]+'，“'+f2+'”のときは'+names[1]+'，“'+f3+'”のときは'+names[2]+'の牛乳とする。'),
   p('③ 牧場区分が“'+f1+'”，“'+f2+'”，“'+f3+'”及び“'+mix+'”以外のときは，エラーであり，このレコードの内容をエラーファイルに出力する。'),
   p('エラーとなったものを除き，製造日ごとに'+names[0]+'，'+names[1]+'及び'+names[2]+'の牛乳の必要量をそれぞれ集計し，集計ファイルに出力する。入出力関連図を図4に，モジュール構造図を図5に示す。'),
   draw('io',0,'図4　入出力関連図')],
  [draw('hierarchy',0,'図5　モジュール構造図'),
   p('設問1　図6は，主処理と必要量計算の流れ図である。図中の空欄に入れる正しい答えを，解答群の中から選べ。'),
   draw('dispatch',0,'図6　主処理と必要量計算の流れ図')],
  [ ...(print?bank('aに関する解答群',aOptions):[]), ...(print?bankBlocks('b，cに関する解答群',bankLogic):[])],
  [p('設問2　図7は，混合の流れ図である。図中の空欄に入れる正しい答えを，解答群の中から選べ。'),
   draw('mix-flow',index,'図7　混合の流れ図'),
   p('注　“牛乳の必要量”は，必要量ファイルから入力した値である。“'+names[first]+'の割合”及び“'+names[second]+'の割合”は，標準混合割合ファイルの値である。'+vars[0]+'，'+vars[1]+'及び'+vars[2]+'には，それぞれ，'+names[0]+'，'+names[1]+'及び'+names[2]+'の牛乳の必要量を格納する。除算の計算結果は，小数点以下を切り捨てる。'),
   ...(print?bank('解答群',amounts):[]),
   p('設問3　図5中の初期化を除く第3階層及び第4階層の最下位のモジュールのうち，“牧場区分”によって処理を分ける必要があるものを，解答群の中から選べ。ここで，初期化モジュールは，作業用記憶の初期化だけを行うものとする。'),
   ...(print?bank('解答群',lastOptions):[])],
 ];
}

