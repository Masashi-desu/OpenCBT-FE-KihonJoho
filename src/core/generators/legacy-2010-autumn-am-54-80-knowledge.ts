function sameChoices(
  number: keyof typeof source, prompt: string, subjects: readonly [string, string, string],
  keys: readonly [number, number, number], explanation: string,
): Series['variants'] {
  return [
    scenario(prompt.replace('{subject}', subjects[0]), source[number].choices, keys[0], explanation),
    scenario(prompt.replace('{subject}', subjects[1]), source[number].choices, keys[1], explanation),
    scenario(prompt.replace('{subject}', subjects[2]), source[number].choices, keys[2], explanation),
  ];
}

