import { choiceBody, define, source } from './legacy-2011-autumn-am-01-26-shared';

type Variant = { prompt: string; correctIndex: number; explanation: string; choices?: readonly string[] };
type Related = readonly [prompt: string, correctIndex: number, explanation: string];
const related = (rows: readonly Related[]): Variant[] => rows.map(([prompt, correctIndex, explanation]) => ({ prompt, correctIndex, explanation }));

function knowledge(number: number, condition: string, review: string, explanation: string, variants: readonly Variant[]) {
  const original = source[number];
  const cases: readonly Variant[] = [{ prompt: original.prompt, correctIndex: 'アイウエ'.indexOf(original.sourceKey), explanation }, ...variants];
  return define(number, condition, cases.length, review, index => {
    const item = cases[index], choices = item.choices ?? original.choices;
    return choiceBody(item.prompt, choices, choices[item.correctIndex], item.explanation);
  });
}

