export const spring2006Pm5 = define(
  5, '売上データの前処理と整列済みファイルの突合せ', '設問1=イ・カ／a・b=イ・ケ（順不同）／c=イ／d=ウ',
  '抽せん対象となる購入額と，突合せに使う顧客番号の間隔',
  'キャンペーン購入額とテストデータの顧客番号・購入額を変え，応募者ファイルとの大小・等値の3条件を検査する。',
  '突合せに必要な前処理、各ファイルの形式、6桁顧客番号、購入日付順と応募者一意、対象期間の注を保持。設問1は二つを一欄のチェックリストから選ぶ。設問2はa・bの二欄で順不同。設問3は元と同じ昇順4択で間隔と不一致の顧客番号の位置を可変にし、全組を独立照合する。作品や実在企業・製品資料の出典表示なし。',
  index => {
    const { applicants, ids, minimum } = campaignCases[index];
    const [first, last] = applicants;
    const eligible = ids.flatMap((id, index) => id < ids[last] && id !== ids[first] ? [index] : []);
    if (eligible.length !== 1) throw Error('CAMPAIGN_BRANCH_COVERAGE');
    const [unmatched] = eligible;
    const leading = unmatched < first
      ? 'c='+ids[unmatched]+'は応募者の先頭'+ids[first]+'より小さいので，最初に中間側を進める。次にdが先頭の応募者より大きいので応募者側を進める。'
      : 'c='+ids[unmatched]+'は応募者の先頭'+ids[first]+'より大きいので，最初に応募者側を進める。次にcが応募者の末尾より小さいので中間側を進める。';
    const body = answers(
      [strings(preChoices), strings(endChoices), strings([...ids])],
      [
        { ids: ['s1-1', 's1-2'], labels: ['設問1', '設問1'], bank: 0, correct: [1,5] },
        { ids: ['a', 'b'], labels: ['a','b'], bank: 1, correct: [1,8] },
        single('c', 'c', 2, unmatched), single('d', 'd', 2, last),
      ],
    );
    const partAnswers = body.partAnswers!.map((answer): PartAnswer =>
      answer.kind === 'unordered' && answer.partIds.includes('part-s1-1') ? { ...answer, presentation: 'checklist' } : answer);
    return {
      prompt: spring2006Pm5Pages(index, false).flat(), ...body, partAnswers,
      explanation: '前処理は購入が'+money(minimum)+'円以上の伝票のうち対象期間内のものを抽出し，顧客番号順に整列する。応募の有無は後段で判定する。突合せは小さい側を読み進め，同じ番号ならあて先を1件出力して両方を進める。どちらか一方が尽きたらもう共通のレコードはない。aとbの順は問わない。テストでは'+
        leading+'最後にd='+ids[last]+'で等しくなり，三つの処理を実行できる。',
    };
  },
);
