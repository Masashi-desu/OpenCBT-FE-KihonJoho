export const row = (prompt: string, choices: readonly string[], key: number, explanation: string): GeneratedBody =>
  ({ prompt: [p(prompt)], choices: strings([...choices]), correctIndex: key, explanation });
export const original = (number: number, explanation: string): GeneratedBody =>
  row(source[number].prompt, source[number].choices, 'アイウエ'.indexOf(source[number].key), explanation);

type KnowledgeCase = { target: string; choice: number; why: string };
function byTarget(number: number, from: string, cases: readonly KnowledgeCase[], choices = source[number].choices) {
  return (index: number) => {
    const { target, choice, why } = cases[index];
    return index === 0 ? original(number, why) : row(source[number].prompt.replace(from, target), choices, choice, why);
  };
}

