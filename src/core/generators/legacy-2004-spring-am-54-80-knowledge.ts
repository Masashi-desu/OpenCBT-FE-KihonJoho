export function knowledge(number: number, index: number): GeneratedBody {
  const original = source[number];
  if (index === 0) return body(original.prompt, original.choices, 'アイウエ'.indexOf(original.key), explanations[number]);
  const variant = variants[number](index - 1);
  return body(variant.prompt, variant.choices ?? original.choices, variant.correctIndex, variant.explanation ?? explanations[number]);
}
