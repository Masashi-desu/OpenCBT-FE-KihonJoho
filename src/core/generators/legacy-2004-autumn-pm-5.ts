import { p, strings } from './definition';
import { answers, bank, bankBlocks, define, single } from './legacy-2004-autumn-pm-01-05-shared';
import { draw } from './legacy-2004-autumn-pm-01-05-figures';
import { fLayouts, salesCases } from './legacy-2004-autumn-pm-01-05-models';

const order=['売上金額の昇順','売上金額の降順','商品コードの昇順','商品コードの降順','全支店データの順位の昇順','全支店データの順位の降順'];
const fmt=(value:number)=>value.toLocaleString('en-US');
const recordOptions=()=>fLayouts.map((_,i)=>[draw('f-option',i,'Fファイルのレコード様式')]);
function counts(i:number) {
  const {branches,total,mean,limit}=salesCases[i];
  return [branches*limit,mean,total,5*total,branches*mean,branches*total,Math.floor((branches+limit)/2)*total,limit*total].map(fmt);
}
export function autumn2004Pm5Pages(i:number,print=true) {
  const {branches,total,mean,limit}=salesCases[i], quantity=counts(i);
  return [
    [p('プログラム設計に関する次の記述を読んで，設問1，2に答えよ。'),
      p('ある小売業者は，本社と'+branches+'の支店からなっている。毎日各支店から本社に次に示すレコード様式の各商品の売上実績ファイルが送付される。'),
      draw('sales-layout',0,'売上実績ファイルのレコード様式'),
      p('本社でまとめられた売上実績ファイルは，支店コード別，商品コード別で昇順に整列されている。扱う商品の種類の総数は'+fmt(total)+'種類であり，各支店で取扱いのない商品及び売上げがない商品も売上金額が0として記録されている。各支店では平均'+fmt(mean)+'種類の商品が取り扱われている。'),
      p('本社では，売上実績ファイルから支店別の売上実績表を作成しており，全支店での売上金額の多い順に'+limit+'商品を選び，それらの商品が各支店では何番目の売上げであったかを，全支店での順位とともに図1に示すように印字する。売上金額が等しい商品には，商品コードの昇順に順位を付ける。'),
      p('なお，この問題において整列処理は安定であるとする。'),
      draw('report-all',i,'図1　全支店での売上順位を基にした売上実績表'),
      p('支店別の売上実績表を作成する方法について，図2に示す処理の流れ図を作成した。'),
      p('〔売上上位'+limit+'商品の抽出〕'),
      p('商品コードをキーとして売上実績ファイルを整列する。商品コードごとの販売数量の合計と売上金額の合計とを計算し，売上金額の多い順に上位'+limit+'商品をFファイル'+(print?'':'に出力する。'))],
    [...(print?[p('に出力する。')]:[]),p('〔支店ごとの順位付け〕'),
      p('支店コード，売上金額（降順）をキーとして売上実績ファイルを整列する。支店ごとに売上金額の多い順に支店データの順位を付け，Gファイルに出力する。'),
      p('〔全支店データと支店別データの照合〕'),
      p('全支店データ（Fファイル）をメモリに格納した後，支店別データ（Gファイル）と照合して，1レコードに編集した次の様式のHファイルを作成する。'),
      draw('joined-layout',0,'Hファイルのレコード様式'),
      p('〔支店別売上実績表の作成〕'),
      p('支店コード，全支店データの順位をキーとしてHファイルを整列する。商品名称表示のために商品マスタファイルを参照しながら，支店別に売上実績表を印字する。'),
      draw('pipeline-all',i,'図2　全支店での売上順位を基にした売上実績表の作成処理')],
    [p('設問1　次の記述中の空欄に入れる正しい答えを，解答群の中から選べ。'),
      p('図2の処理で，Fファイルとして必要最小限の項目をもつレコード様式は［a］である。また，Hファイルのレコード件数は［b］件である。'),
      ...(print?[...bankBlocks('aに関する解答群',recordOptions()),...bank('bに関する解答群',quantity)]:[]),
      p('設問2　次の記述中の空欄に入れる正しい答えを，解答群の中から選べ。'),
      p('各支店で売上金額の多い順に'+limit+'商品を選び，それらの商品が全支店では何位の売上げであったかを，支店データの順位とともに図3に示すように印字する。なお，売上金額が等しい商品は，商品コードの昇順に順位を付ける。')],
    [draw('report-branch',i,'図3　支店ごとの売上順位を基にした売上実績表'),
      p('この売上実績表を作成するために，図4に示す処理の流れ図を作成した。'),
      p('〔売上合計の計算〕'),
      p('商品コードをキーとして売上実績ファイルを整列する。商品コードごとの販売数量の合計と売上金額の合計とを計算し，全件をLファイルに出力する。'),
      p('〔ステップ1〕'),p('Lファイルを［c］に整列し，全支店順位を付けて，全件をL1ファイルに出力する。'),
      p('〔ステップ2〕'),p('L1ファイルを［d］に整列し，L2ファイルを作成する。'),
      p('〔売上上位商品の抽出〕'),
      p('支店コード，売上金額（降順）をキーとして売上実績ファイルを整列する。支店ごとに商品の売上金額による順位を付け，売上実績表の作成に必要な［e］件だけをMファイルに出力する。'),
      p('〔商品コードで整列〕'),p('Mファイルを商品コードの昇順に整列し，M1ファイルを作成する。'),
      p('〔全支店データと支店別データの照合〕'),p('L2ファイル（全支店データ）とM1ファイル（支店別データ）とを照合して，Nファイルを作成する。'),
      p('〔支店別売上実績表の作成〕'),
      p('支店コード，その支店データの順位をキーとしてNファイルを整列する。商品名称表示のために商品マスタファイルを参照しながら，支店別に売上実績表を印字する。')],
    [draw('pipeline-branch',0,'図4　支店ごとの売上順位を基にした売上実績表の作成処理'),
      ...(print?[...bank('c，dに関する解答群',order),...bank('eに関する解答群',quantity)]:[])],
  ];
}
export const autumn2004Pm5=define(
  5,'全支店と各支店の売上順位・実績表','a=オ／b=ア／c=イ／d=ウ／e=ア',
  '支店数・商品数・印字対象となる上位件数',
  '支店数、商品総数、平均取扱数、上位の商品数と図の上位範囲を同じ条件で変更する。',
  '売上0の商品も対象、安定整列、売上金額の降順と同額の商品コード昇順、全支店と支店別の集計・照合を維持。',
  i=>{
    const {limit,branches}=salesCases[i];
    const quantities=counts(i);
    return {prompt:autumn2004Pm5Pages(i,false).flat(),...answers([recordOptions(),strings(quantities),strings(order)],[
      single('a','a',0,4),single('b','b',1,0),single('c','c',2,1),single('d','d',2,2),single('e','e',1,0),
    ]),explanation:'Fファイルは全支店集計のため商品コード・販売数量合計・売上金額合計が必要で，元の年月日や支店コードは不要。全支店順位はFの出力順から分かる。'+
      branches+'支店それぞれに'+limit+'件を照合するのでHは'+quantities[0]+'件。ステップ1は売上金額の降順で，同額なら安定整列により先に並べた商品コード順を保つ。'+
      'ステップ2はM1と同じ商品コードの昇順とし，順に照合できるようにする。Mには各支店の上位だけを出力するので'+quantities[0]+'件。'};
  },{answerVariation:'fixed'},
);
