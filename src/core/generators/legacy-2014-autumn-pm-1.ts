const choices=allBanks[0] as {purpose:string[];rules:string[];ssh:string[];key:string[]};
function networkFields(i:number){
  const n=networkCases[i];
  return {
    rules:[
      n.mag+','+n.https,n.mag+','+n.dbPort,n.member+','+n.dbPort,n.web+','+n.https,n.web+','+n.dbPort,'if0,'+n.https,
    ],
    ssh:[
      n.client+','+n.web+','+n.ssh,n.client+',if0,'+n.ssh,n.web+','+n.client+','+n.ssh,'if0,'+n.client+','+n.ssh,
    ],
  };
}

