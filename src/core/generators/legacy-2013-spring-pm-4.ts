import { securityCases } from './legacy-2013-spring-pm-01-04-models';
import { draw } from './legacy-2013-spring-pm-01-04-figures';

const card = [
  '一部が破損しても利用できるICカード', '外部から強い衝撃があっても変形しないICカード',
  '内部情報に外部から不正にアクセスできないICカード', '返却後に，再利用できるICカード',
];
const date = 'ICカード利用日時';
const reader = 'ICカード読取り装置識別番号';
const cardId = 'ICカードID';
const userId = '利用者ID';
const log = [
  [reader, cardId, userId].join('，'),
  [date, cardId, userId].join('，'),
  [date, reader, cardId, userId].join('，'),
  [date, reader, '入室許可の状態'].join('，'),
];
const arrows = ['α', 'β', 'γ', 'δ'];
const states = ['①', '②', '③', '④', '⑤'];

function events(tries: number) {
  return [tries + '回連続してパスワードを誤入力', '社員の入社', '入退室管理システムの異常', 'プロジェクトの終了'];
}

export function spring2013Pm4Pages(index: number) {
  const input = securityCases[index];
  const waitingPolicy = input.availableBetweenProjects
    ? '\nなお，協力社員で契約が有効なままプロジェクトの間に待機する期間がある場合，その期間の入室許可の状態は“執務室だけ許可”とする。'
    : '';
  return [
    [
      p('問4　ICカードを利用した入退室管理システムに関する次の記述を読んで，設問1〜5に答えよ。'),
      p('J社は，中規模のSIベンダであり，外部の協力が必要なシステム開発のときには，プロジェクトごとに協力会社と契約している。J社には，開発室と執務室があり，開発室には執務室を通って入退室する。各室の出入口の内側と外側にICカード読取り装置が設置されており，社員と，協力会社社員（以下，協力社員という）の入退室は，入退室管理システムで管理されている。社員及び協力社員は入退室時に，ICカードを読取り装置にかざし，入室時には更にパスワードを入力することによって，出入口の扉が開錠される。また，扉が閉められると，自動的に施錠される。'),
      p('J社の入退室管理システムのセキュリティ要件は，次のとおりである。'),
      draw('securityPolicy', index, 'J社の入退室管理システムのセキュリティ要件'),
      p('なお，J社では，社員や協力社員が，同時に複数のプロジェクトに参画することはない。'),
    ],
    [
      p('〔入退室管理システムの説明〕'),
      p('入退室管理システムが管理する，利用者情報のうち主なものを表1に，入退室情報のうち主なものを表2に示す。'),
      draw('userInfo', index, '表1　主な利用者情報'),
      table('表2　主な入退室情報', ['入退室情報', '説明'], [
        [date, '出入口でICカードをかざした年月日時分秒'],
        [reader, '出入口に設置しているICカード読取り装置を識別する一意の番号'],
        [cardId, '出入口でかざしたICカードのID'],
      ]),
      p('〔入退室管理システムの運用の説明〕'),
      p('セキュリティ管理者は，入室申請の受付，入退室管理システムへの利用者情報の設定，ICカードの発給を担当する。'),
      p('（1）社員に対する運用は，次のとおりである。\n（a）社員の入社時に，入退室管理システムの運用ルールを説明した後，ICカードを発給し，パスワードを仮パスワードから変更させる。これで社員の執務室への入室が可能となる。\n（b）プロジェクトの開始時及び終了時に，プロジェクトマネージャ（以下，PMという）からの申請を受けて，開発室へのプロジェクトメンバの“入室許可の状態”の設定を変更する。'),
    ],
    [
      p('（c）退職時には，ICカードを返却させるとともに，“有効期間の終了日”に退職日を，“ICカードの状態”に“返却”を設定する。'),
      p('（2）協力社員に対する運用は，次のとおりである。\n（a）プロジェクトの開始時に，PMからの申請を受けて，当該協力社員の利用者情報を登録すると同時に“入室許可の状態”を設定し，PMに協力社員用のICカードを発給する。ICカードを受領したPMは入退室管理システムの運用ルールを協力社員に説明した後，ICカードを配布してパスワードを仮パスワードから変更させる。\n（b）契約の終了時は，協力社員に配布していたICカードの返却をPM経由で受けて，“有効期間の終了日”に契約の終了日を，“ICカードの状態”に“返却”を設定する。' + waitingPolicy),
      p('（3）利用者情報の削除処理は，次のとおりである。\n（a）“有効期間の終了日”を過ぎ，かつ，“ICカードの状態”が“返却”の利用者情報は，週末のバッチ処理でバックアップメディアに保存した上で，入退室管理システムから削除する。\n（b）返却されたICカードは，後日再利用する。'),
      p('入退室管理システムで管理する，社員を対象にした“ICカードの状態”，“入室許可の状態”及び“入室可能な部屋”の関係を表す状態遷移図を，図1に示す。'),
      draw('security', 0, '図1　社員を対象とした状態遷移図'),
    ],
    [
      p('設問1　〔J社の入退室管理システムのセキュリティ要件〕の説明中の下線①のICカードの説明として正しい答えを，解答群の中から選べ。'),
      ...bank('解答群', card),
      p('設問2　〔J社の入退室管理システムのセキュリティ要件〕の説明中の下線②のログとして収集するのが適切な情報を，解答群の中から選べ。'),
      ...bank('解答群', log),
      p('設問3　図1の［a］に入れる正しい答えを，解答群の中から選べ。'),
      ...bank('解答群', events(input.tries)),
    ],
    [
      p('設問4　図1を基に，最少の変更で，協力社員を対象にした状態遷移図を作成するとした場合，' +
        (input.availableBetweenProjects ? 'プロジェクト間の待機期間中に' : '') +
        '協力社員が契約を終了して遷移する矢印として適切な答えを，解答群の中から選べ。'),
      ...bank('解答群', arrows),
      p('設問5　J社では内部監査時に，開発室及び執務室の入退室に関する調査を行ったところ，入退室管理システムのログに，入室履歴のない退室履歴や退室履歴のない入室履歴が見つかった。そこで，更に調査した結果，直前に入退室した者がいるとき，扉が施錠される前に，自分のICカードを使わずに入退室する者がいることが分かった。そこで，入退室時には自分のICカードを必ず読取り装置にかざさせる対策として，教育を実施するとともに入退室管理システムで管理する現在の状態遷移を変更することにした。図1の状態番号のうち，入室履歴又は退室履歴のない者がICカードをかざして退室又は入室しようとした際に，遷移する先として適切な状態番号を，解答群の中から選べ。'),
      ...bank('解答群', states),
    ],
  ];
}

