function attackChoices(index: number) {
  const { company, input } = incidents[index];
  return [
    '攻撃者がDNSに登録されたドメインの情報を改ざんすることによって，利用者をフィッシングサイトに誘導し，そこで入手した利用者IDとパスワードを用いて，データベースを不正に操作した。',
    '攻撃者が，' + company + '社のWebサイトの' + (index ? '“' + input + '”の入力項目' : '入力項目') + 'に対し，命令文を送り込むことによって，データベースを不正に操作した。',
    '攻撃者が' + company + '社のデータベースの管理ツールを入手し，管理ツール経由で直接' + company + '社のデータベースを不正に操作した。',
    '攻撃者がネットワーク上で情報の盗聴を行い，' + company + '社のデータベースの管理者のIDとパスワードを入手し，データベースを不正に操作した。',
  ];
}

function memberChoices(index: number) {
  const { company, credentials } = incidents[index];
  return [
    credentials ? '漏えいしたパスワードの不正利用を防ぐために，パスワードの再設定を全会員に依頼する。'
      : '安易なパスワードの設定を防止するために，パスワードは英字，数字，記号が混在する8文字以上のものにするよう会員に依頼する。',
    '攻撃を受けた場合の被害を抑えるために，メールマガジン購読だけを利用する会員の会員情報を格納したデータベースと商品の購入を行う会員の会員情報を格納したデータベースとを分離し，商品の購入を行う会員だけには，利用者ID及びパスワードの変更を依頼する。',
    '個人情報の目的外利用を避けるために，' + company + '社が取得する個人情報の利用目的に事故の対応を追加し，同意を会員に依頼する。',
    'クレジットカード情報が漏えいしている場合の不正利用を防止するために，登録されたクレジットカードの停止及び番号変更の手続を会員に依頼する。',
  ];
}

