import { p, strings, table } from './definition';
import { answers, bank, define, single } from './legacy-2011-special-pm-01-04-shared';
import { draw } from './legacy-2011-special-pm-01-04-figures';
import { orderOptions, priorityOptions, schedulingCase } from './legacy-2011-special-pm-01-04-models';

const overhead = 'なお，プロセスの登録と取出し，及び中断の処理でのオーバヘッドは考えない。また，CPUを割り当てられたプロセスは，タイムクウォンタム以外で中断することはない。';

export function special2011Pm2Pages(index: number) {
  const { jobs, quantum, priorityJobs, avgChoices } = schedulingCase(index);
  return [[
    p('問2　CPUの割当て方式に関する次の記述を読んで，設問1，2に答えよ。'),
    p('オペレーティングシステムの役割の一つとして，プロセスにCPUを割り当てることがある。そして，プロセスの実行順序を決定する方式には，次のようなものがある。'),
    p('（1）到着順方式'),
    p('到着順にプロセスを待ち行列の末尾に登録する。実行中のプロセスが終了すると，待ち行列の先頭からプロセスを一つ取り出して実行を開始する。'),
    p('到着順方式を図1に示す。待ち行列に登録されているプロセスの状態を実行可能状態，実行中のプロセスの状態を実行状態と呼ぶ。'),
    draw('queues', 0, '図1　到着順方式'),
    p('注　○はプロセスを表す。'),
    p('（2）ラウンドロビン方式'),
    p('到着順にプロセスを待ち行列の末尾に登録する。実行中のプロセスが終了すると，待ち行列の先頭からプロセスを一つ取り出して実行を開始する。また，実行中のプロセスが一定時間（以下，タイムクウォンタムという）を経過したら，実行を中断して，待ち行列の末尾に再登録し，待ち行列の先頭からプロセスを一つ取り出して実行を開始する。'),
    p('ラウンドロビン方式を図2に示す。'),
    draw('queues', 1, '図2　ラウンドロビン方式'),
    p('注　○はプロセスを表す。'),
  ], [
    p('これらの方式の効率を示す指標としてターンアラウンドタイムがある。ここで，ターンアラウンドタイムとは，プロセスが待ち行列に到着してから実行が終了するまでの時間であり，プロセスの実行順序に影響される。'),
    p('なお，このコンピュータシステムのCPUは一つであり，CPUは同時に一つのプロセスしか実行できない。'),
    p('設問1　次の記述中の［空欄］に入れる正しい答えを，解答群の中から選べ。'),
    p('四つのプロセスA〜Dがあり，各プロセスの到着時刻と処理時間を表1に示す。表1において，到着時刻とは，プロセスAが待ち行列に到着した時刻を0としたときの各プロセスが到着する時刻であり，処理時間とは，各プロセスの処理が完了するために必要なCPUの処理時間である。'),
    table('表1　プロセスの到着時刻と処理時間', ['プロセス', '到着時刻（ミリ秒）', '処理時間（ミリ秒）'],
      jobs.map(job => [job.name, String(job.arrival), String(job.duration)])),
    p('このとき，到着順方式におけるターンアラウンドタイムの平均は［a］ミリ秒である。そして，タイムクウォンタムが' +
      quantum + 'ミリ秒のとき，ラウンドロビン方式におけるターンアラウンドタイムの平均は［b］ミリ秒である。ここで，プロセスAが到着したとき，実行可能状態及び実行状態のプロセスはないものとする。'),
    p(overhead),
    ...bank('解答群', avgChoices),
  ], [
    p('設問2　次の記述中の［空欄］に入れる正しい答えを，解答群の中から選べ。'),
    p('プロセスの実行順序を決める別の方式に優先度順方式がある。優先度順方式の例を図3に示す。プロセスにはあらかじめ優先度が付けてあり，待ち行列は優先度ごとに用意してある。ここで，優先度は1〜10の10種類で，値の大きい方が優先度は高い。'),
    draw('queues', 2, '図3　優先度順方式の例'),
    p('注　○はプロセスを表す。'),
    p('この方式では，次のとおりにプロセスの実行を制御する。'),
    p('① プロセスを優先度に対応した待ち行列の末尾に登録する。'),
    p('② プロセスが登録されている優先度の最も高い待ち行列の先頭からプロセスを一つ取り出して実行を開始する。'),
    p('③ 実行中のプロセスの優先度が2以上のとき，実行時間が' + quantum +
      'ミリ秒経過するごとに優先度を一つ下げる。優先度を下げた結果，実行中のプロセスの優先度が実行可能状態にある優先度の最も高いプロセスよりも低くなった場合，実行中のプロセスを中断して，①に戻る。'),
    p('④ 実行中のプロセスが終了した場合，②に戻る。'),
    p('優先度順方式において，あるプロセスが終了した時点で表2に示す三つのプロセスだけが優先度に対応した待ち行列に登録されていたとする。このとき，三つのプロセスが終了する順番は［c］である。そして，プロセス'),
  ], [
    p('Bの実行が終了したときのプロセスBの優先度は［d］である。ここで，三つのプロセスが終了するまで新たに到着するプロセスはないものとする。'),
    p(overhead),
    table('表2　プロセスの処理時間と優先度の初期状態', ['プロセス', '処理時間（ミリ秒）', '優先度'],
      priorityJobs.map(job => [job.name, String(job.duration), String(job.priority)])),
    ...bank('cに関する解答群', orderOptions),
    ...bank('dに関する解答群', priorityOptions),
  ]];
}

export const legacy2011SpecialPm2Definition = define(2, 'CPUの割当て方式',
  '1a=オ・1b=ウ・2c=ウ・2d=オ', 'プロセスの到着時刻・処理時間・初期優先度',
  '到着順方式とラウンドロビン方式の到着時刻・処理時間、優先度順方式の初期状態を変えます。',
  'p.9〜12。CPUは一つ，待ち行列と再登録の向き，ターンアラウンドは到着から終了，' +
  'オーバヘッドなし，初期空・新規到着なし，20ミリ秒ごとの優先度低下と「低くなった場合」を保持。小数1桁，候補は平均実行・待ち・終了時刻の混同を含む。', index => {
    const { a, b, order, d, fcfs, roundRobin, avgChoices, priorityJobs, quantum } = schedulingCase(index);
    return {
      prompt: special2011Pm2Pages(index).flat(),
      ...answers([strings(avgChoices), strings(orderOptions), strings(priorityOptions.map(String))], [
        single('1a', '設問1 a', 0, avgChoices.indexOf(a.toFixed(1))), single('1b', '設問1 b', 0, avgChoices.indexOf(b.toFixed(1))),
        single('2c', '設問2 c', 1, orderOptions.indexOf(order)), single('2d', '設問2 d', 2, priorityOptions.indexOf(d)),
      ]),
      explanation: 'ターンアラウンドタイムは終了時刻から到着時刻を引く。A〜Dは到着順方式で' +
        fcfs.join('，') + 'ミリ秒となり，平均は' + a.toFixed(1) + 'ミリ秒。ラウンドロビン方式では' +
        roundRobin.join('，') + 'ミリ秒となり，平均は' + b.toFixed(1) + 'ミリ秒。優先度順方式では' +
        quantum + 'ミリ秒ごとに実行中の優先度が1まで下がり，待ち行列にそれより高い優先度があれば中断する。' +
        'この条件で追うと' + order + 'の順に終了する。Bの初期優先度は' + priorityJobs[1].priority +
        '，終了までの実行時間は' + priorityJobs[1].duration + 'ミリ秒なので，終了時は' + d + 'となる。',
    };
  });
