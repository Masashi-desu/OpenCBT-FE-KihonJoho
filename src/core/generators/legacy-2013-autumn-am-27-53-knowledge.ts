import { p, strings, type GeneratedBody, type GenerationDefinition } from './definition';
import { legacy2013AutumnAm27To53Source as source } from './legacy-2013-autumn-am-27-53-source';
import { finite2013AutumnAm } from './legacy-2013-autumn-am-27-53-shared';

type Scenario = {
  stem: string;
  index: number;
  explanation: string;
  choices?: readonly string[];
};

function scenario(stem: string, index: number, explanation: string, choices?: readonly string[]): Scenario {
  return { stem, index, explanation, choices };
}

function replaceChoice(number: number, index: number, replacement: string) {
  return source[number].choices.map((choice, i) => i === index ? replacement : choice);
}

function knowledge(number: number, title: string, input: string, notes: string, explanation: string,
  variants: readonly Scenario[], material?: () => GeneratedBody['prompt']): GenerationDefinition {
  const original = source[number];
  const cases = [scenario(original.prompt, 'アイウエ'.indexOf(original.key), explanation), ...variants];
  return finite2013AutumnAm(number, title, input, cases.length, notes, i => {
    const item = cases[i];
    return {
      prompt: [p(item.stem), ...(material?.() ?? [])],
      choices: strings([...(item.choices ?? original.choices)]),
      correctIndex: item.index,
      explanation: item.explanation,
    };
  });
}

