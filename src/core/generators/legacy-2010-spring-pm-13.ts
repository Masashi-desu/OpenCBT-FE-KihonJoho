function quantityFormulas(index: number) {
  const { minimumDrink, minimumDish, minimumTotal, percent } = discountCases[index];
  const rate = percent / 100;
  const a = `B2≧${minimumDrink}`;
  const b = `B3≧${minimumDish}`;
  const total = `(B2＋B3)≧${minimumTotal}`;
  const correct = `論理和(論理積(${a},${b}),${total})`;
  const swapped = `論理積(論理和(${a},${b}),${total})`;
  return [
    `B14−IF(${correct},${rate},0)＊H13`, `B14−IF(${swapped},${rate},0)＊H13`,
    `(1＋IF(${correct},${rate},0))＊B14`, `(1＋IF(${swapped},${rate},0))＊B14`,
    `(1−IF(${correct},${rate},1))＊B14`, `(1−IF(${swapped},${rate},1))＊B14`,
    `(1−IF(${swapped},${rate},0))＊B14`, `(1−IF(${correct},${rate},0))＊B14`,
  ];
}
