type Variant = {
  stem: string;
  answer: number;
  explanation: string;
  choices?: readonly string[];
  material?: string;
};
function variation(stem: string, answer: number, explanation: string, choices?: readonly string[], material?: string): Variant {
  return { stem, answer, explanation, choices, material };
}

function knowledge(number: number, title: string, field: string, notes: string, baseExplanation: string, alternatives: readonly Variant[]) {
  const original = source[number];
  const cases = [variation(original.prompt, 'アイウエ'.indexOf(original.key), baseExplanation, original.choices, original.material), ...alternatives];
  return finite(number, title, field, cases.length, notes, i => {
    const { stem, answer, explanation, choices, material } = cases[i];
    return {
      prompt: [p(stem), ...(material?.split('\n').map(p) ?? [])],
      choices: strings([...(choices ?? original.choices)]),
      correctIndex: answer,
      explanation,
    };
  });
}

