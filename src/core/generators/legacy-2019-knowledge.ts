function define(number: number, title: string, answer: string, count: number, reference: number,
  build: GenerationDefinition["build"], notes: string, fixed = false): GenerationDefinition {
  return {
    source: `2019h31h-fe-am-${number}`, title, sourceAnswer: answer,
    fields: [field("conceptCondition", 0, count - 1)], reference: [reference],
    ...(fixed ? { answerVariation: "fixed" as const } : {}),
    notes: variableNotes + " " + notes,
    build: values => {
      if (values.length !== 1 || !Number.isInteger(values[0]) || values[0] < 0 || values[0] >= count)
        throw Error("PARAMETER_CONSTRAINT");
      return build(values);
    },
  };
}

