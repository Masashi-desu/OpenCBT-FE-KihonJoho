const countBank=['1','2','3','4','5','6'];
const processBank=['処理1','処理1，処理2','処理1，処理2，処理3','処理1，処理3','処理2','処理2，処理3','処理3'];
const assignBank=['JIGEN ← 0','JIGEN ← I_JIGEN','NENJI ← 0\nYOBI ← 0\nJIGEN ← 0','YOBI ← 0\nJIGEN ← 0'];
const initialBank=['ERROR ← 偽','ERROR ← 偽\nNENJI ← 0','ERROR ← 偽\nNENJI ← 0\nYOBI ← 0',
  'ERROR ← 偽\nNENJI ← 0\nYOBI ← 0\nJIGEN ← 0','ERROR ← 偽\nNENJI ← 0\nYOBI ← 0\nJIGEN ← 0\nHYOJJUN ← 0'];
const conditionBank=['HYOJJUN−1：I_HYOJJUN','HYOJJUN−1：I_HYOJJUN＋1','HYOJJUN＋1：I_HYOJJUN',
  'HYOJJUN＋1：I_HYOJJUN−1','HYOJJUN：I_HYOJJUN'];
const signBank=['＝','＞','＜','≠','≦','≧'];
const codeBanks=[assignBank,initialBank,conditionBank,signBank];

export function spring2005Pm5Pages(index:number,print=true) {
  const {caption}=schedule(index);
  return [
    [p('プログラム設計に関する次の記述を読んで，設問1，2に答えよ。'),
      p('ある大学では，既存システムから出力される授業の時間割ファイルを，新システムの入力とするために，ファイル編集プログラムを作成することになった。'),
      p('この大学の時間割では，同じ年次，曜日，時限に複数の科目が存在する場合がある。'),
      p('既存システムで出力ファイルを作成した後に，時間割の変更が生じた場合，担当者が出力ファイルを修正してから，編集プログラムに入力することも想定されている。'),
      p('さらに，新システムでは，入力レコードの各項目の値の範囲及び順序の誤りを検査する機能をもっていないので，これらの検査も編集プログラムの機能に含めることにした。'),
      p('この大学の時間割の例，既存システムの出力ファイル，新システムの入力ファイル及び編集プログラムの流れを次に示す。'),
      p('〔時間割の例〕'),draw('timetable',index,'図1　時間割の例')],
    [p('〔既存システムの出力ファイル〕'),
      p('既存システムは，次の様式で，年次，曜日，時限，表示順をキーとして，昇順に時間割ファイルのレコードを出力する。'),
      p('年次：1～4年次を，数字1～4で表す。'),
      p('曜日：日～土の曜日を，数字1～7で表す。'),
      p('時限：1～9時限（最大9時限まで）を，数字1～9で表す。'),
      p('表示順：同一年次の同一曜日，同一時限の科目の表示の順番を，1から始まる連続した数字で表す。'),
      p('科目名：“哲学”，“政治学”などを，文字列で記述する。'),
      p('教員名：“井上紘司”，“小林慎一”などを，文字列で記述する。'),
      p('レコード様式は，次のとおりである。'),draw('record-layout',0,'既存システムの出力レコード'),
      p('〔新システムの入力ファイル〕'),
      p('年次，曜日，時限，科目名，教員名は，それぞれ1レコードとして入力する。ただし，既存システムの出力と同じ順番を維持する。'),
      p('複数の科目を，同一年次の同一曜日，同一時限に指定する場合は，登録する順に，科目名と教員名の組を連続して入力する。'),
      p('年次，曜日，時限のレコードは，それぞれが変わるときにだけ入力する。'),
      p('レコードの内容は，次に示す年次，曜日，時限，科目名，教員名のいずれかである。年次，曜日，時限は，先頭の半角英字1文字と，それに続く半角数字1文字で指定する。科目名と教員名は，全角の文字列で指定する。'),
      p('年次：1～4年次を，記号G1～G4で表す。'),
      p('曜日：日～土の曜日を，記号D1～D7で表す。'),
      p('時限：1～9時限（最大9時限まで）を，記号T1～T9で表す。'),
      p('科目名：“哲学”，“政治学”などを，文字列で記述する。'),
      p('教員名：“井上紘司”，“小林慎一”などを，文字列で記述する。')],
    [p('既存システムの出力例の一部と対応する新システムへの入力を図2に示す。'),
      draw('file-example',index,'図2　各ファイルの内容の例')],
    [p('〔プログラムの流れ〕'),draw('editor-flow',0,'図3　編集プログラムの流れ'),
      p('変数の説明'),
      p('ERROR：直前の処理（値の範囲の検査，主処理）で誤りを検出したときに値が真に設定される変数。')],
    [p('注：図中の網掛けの部分は，記述を省略している。'),
      draw('main-flow',0,'図4　主処理の流れ'),
      p('変数の説明'),
      table('主処理で使用する変数',['入力レコード','意味','保持値','意味'],[
        ['I_NENJI','入力レコードの年次の値をもつ変数','NENJI','年次を格納する変数'],
        ['I_YOBI','入力レコードの曜日の値をもつ変数','YOBI','曜日を格納する変数'],
        ['I_JIGEN','入力レコードの時限の値をもつ変数','JIGEN','時限を格納する変数'],
        ['I_HYOJJUN','入力レコードの表示順の値をもつ変数','HYOJJUN','表示順を格納する変数'],
        ['I_KAMOKU','入力レコードの科目名の値をもつ変数','',''],
        ['I_KYOIN','入力レコードの教員名の値をもつ変数','',''],
      ])],
    [p('設問1　編集プログラムの振る舞いに関する次の記述中の空欄に入れる正しい答えを，解答群の中から選べ。'),
      p('既存システムの出力ファイルと，新システムへの入力ファイルの特徴から，編集プログラムが出力するレコード件数は，正しい入力レコード1件に対し，最小で［a］，最大で［b］となる。'),
      p('図1の時間割を既存システムが出力し，それをそのまま編集プログラムに入力した場合，'+caption+'の入力レコードに対して，主処理中の処理1～4のうち，実行されるのは［c］及び処理4である。'),
      ...(print?[...bank('a，bに関する解答群',countBank),...bank('cに関する解答群',processBank)]:[]),
      p('設問2　図3及び図4中の各処理の内容に関する次の記述中の空欄に入れる正しい答えを，解答群の中から選べ。'),
      p('条件判定に用いる変数（NENJI，YOBI，JIGEN，HYOJJUN）の新しい値の設定又はこれらの変数の必要最小限の初期化は，主処理中の処理1～4の中で行っている。このうち処理3の網掛けの部分は，［d］である。また，編集プログラムの最初に行う，初期値設定での必要十分な変数の初期化は，［e］である。'),
      p('主処理中の破線で囲った部分の条件Xは，［f］であり，判定Yは，［g］である。')],
    print?codeBanks.flatMap((items,i)=>bankBlocks('defg'[i]+'に関する解答群',asCode(items))):[],
  ];
}
export const spring2005Pm5=define(
  5,'時間割ファイルの編集と入力順序の検査','a=イ／b=オ／c=カ／d=イ／e=イ／f=ウ／g=ア',
  '時間割で追跡する科目と所属年次・曜日・時限',
  '問う科目を変え、図1の時間割と図2の入出力例を変更後のレコードに合わせる。',
  '年次・曜日・時限の階層、表示順の連続性、順序検査、記録の粒度、フローチャートの分岐と図の注記を保持。',
  index=>{
    const {caption,processes}=schedule(index);
    const which=processes.map(n=>'処理'+n).join('，');
    return {prompt:spring2005Pm5Pages(index,false).flat(),...answers([strings(countBank),strings(processBank),...codeBanks.map(items=>asCode(items))],[
      single('a','a',0,1),single('b','b',0,4),single('c','c',1,processBank.indexOf(which)),
      single('d','d',2,1),single('e','e',3,1),single('f','f',4,2),single('g','g',5,0),
    ]),explanation:'処理4は科目名と教員名を1件ずつ出力するので最小2件。年次・曜日・時限の三つも出力する場合は最大5件。'+
      caption+'の直前と年次・曜日・時限を比べると，'+which+'と処理4が実行される。'+
      '処理3で新しい時限を出力したらJIGENにI_JIGENを格納し，表示順を0に戻す。最初にNENJIだけを0にすると最初のレコードで必ず処理1・2・3が順に進み，下位の値が初期化される。'+
      'ERRORも偽にしておく。表示順は前の値に1を足した値と等しい必要がある。'};
  },
);
