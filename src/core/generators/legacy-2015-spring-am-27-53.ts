function finite(
  number: number, title: string, inputName: string, count: number, notes: string,
  build: (input: number) => GeneratedBody, fixed = false,
): GenerationDefinition {
  return {
    source: `2015h27h-fe-am-${number}`,
    title, fields: [field(inputName, 0, count - 1)], reference: [0],
    sourceAnswer: originals[number].key,
    version: '3.7.0',
    ...(fixed ? { answerVariation: 'fixed' as const } : {}),
    notes: variableNotes + ' ' + notes,
    build(values) {
      const [input] = values;
      if (values.length !== 1 || !Number.isSafeInteger(input) || input < 0 || input >= count)
        throw new Error('PARAMETER_CONSTRAINT');
      return build(input);
    },
  };
}

type Case = { prompt?: string[]; choices?: string[]; answer?: number; explanation: string };
function knowledge(
  number: number, title: string, inputName: string, notes: string, cases: Case[],
  extraBase: string[] = [],
): GenerationDefinition {
  const { prompt, choices, key } = originals[number], baseIndex = choiceOrder.indexOf(key);
  return finite(number, title, inputName, cases.length, notes, input => {
    const item = cases[input];
    return {
      prompt: (item.prompt ?? [prompt, ...extraBase]).map(p),
      choices: strings(item.choices ?? choices),
      correctIndex: item.answer ?? baseIndex,
      explanation: item.explanation,
    };
  }, cases.every(item => (item.answer ?? baseIndex) === baseIndex));
}

