function family(number: number, title: string, parameter: string, cases: readonly ReviewedCase[], fixedReason?: string): GenerationDefinition {
  return {
    source: `2015h27a-fe-am-${number}`,
    title,
    fields: [field(parameter, 0, cases.length - 1)],
    reference: [0],
    sourceAnswer: 'アイウエ'[cases[0].correct],
    version: '3.2.0',
    ...(fixedReason ? { answerVariation: 'fixed' as const } : {}),
    notes: `${variableNotes} 本文の具体条件を有限${cases.length}件で変え、各条件の四択を査読する。${fixedReason ?? ''}`,
    build(values) {
      const [index] = values;
      if (values.length !== 1 || !Number.isSafeInteger(index) || index < 0 || index >= cases.length) throw Error('PARAMETER_CONSTRAINT');
      const entry = cases[index];
      return { prompt: [p(entry.prompt)], choices: strings([...entry.choices]), correctIndex: entry.correct, explanation: entry.explanation };
    },
  };
}

