const lengths = [[8, 10], [4, 6], [5, 7], [10, 12]] as const;
const methodOptions = [
  '方式1だけ', '方式2だけ', '方式3だけ', '方式1，2だけ', '方式1，3だけ', '方式2，3だけ', '方式1，2，3すべて',
];
function passwordCase(index: number) {
  const [initial, longer] = lengths[index];
  const lengthFactor = 26 ** (longer - initial), alphabetFactor = 2 ** initial;
  const ratios = [longer / initial, 2, 26 * initial, alphabetFactor, 26 * longer, lengthFactor, 2 ** longer]
    .sort((a, b) => a - b).map(formatted);
  return { initial, longer, lengthFactor, alphabetFactor, ratios };
}

