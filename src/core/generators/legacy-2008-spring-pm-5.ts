import { p, strings } from './definition';
import { answers, bank, define, single } from './legacy-2008-spring-pm-01-05-shared';
import { draw } from './legacy-2008-spring-pm-01-05-figures';
import { saleCases } from './legacy-2008-spring-pm-5-model';

function saleBanks(index: number) {
  const { field, newGroup } = saleCases[index];
  return [
    ['集計期間の日付', '集計期間の日付，構成比率', '集計期間の日付，集計種別', '集計期間の日付，順位']
      .map(option => option.replace('集計期間の日付', '集計開始日付，集計終了日付')),
    ['合計した販売金額', '合計した販売数', '集計項目', '商品カテゴリ名', 'メーカコード'],
    ['集計期間のレコードの再抽出', '順位の付与', '商品ファイルとの突合せ', '中間ファイルBの様式への変換', field + 'の昇順に整列'],
    ['（集計種別＝“商品カテゴリ”）AND（集計種別＝“メーカ”）',
      '（集計種別≠“商品カテゴリ”）OR（集計種別≠“メーカ”）',
      '集計種別＝“' + newGroup + '”', '集計種別≠“' + newGroup + '”'],
    ['構成比率の算出', '集計', '順位の付与', '整列2', '整列3'],
  ];
}

export function spring2008Pm5Pages(index: number) {
  const { stores, field, newGroup, primary, secondary, top, ratio } = saleCases[index];
  const banks = saleBanks(index);
  return [[
    p('問5　プログラム設計に関する次の記述を読んで，設問1〜4に答えよ。'),
    p('小売企業のA社には，本社と' + stores + 'か所の店舗がある。店舗では商品を販売しており，販売結果は販売データとして本社にある販売システムで管理されている。今回，A社では，販売データを基に販売構成一覧を作成することにした。'),
    p('〔販売構成一覧作成プログラムの概要〕'),
    p('（1）販売データは，販売番号と商品コードをキーとして販売ファイルに記録される。販売番号は，1回の販売ごとに割り当てる全社で一意となる番号である。販売ファイルのレコード様式を図1に示す。'),
    draw('saleRecord', index, '図1　販売ファイルのレコード様式'),
    p('（2）商品名，商品カテゴリ名及びメーカコードは，商品コードをキーとして商品ファイルに記録されている。商品ファイルのレコード様式を図2に示す。'),
    draw('productRecord', 0, '図2　商品ファイルのレコード様式'),
    p('（3）販売構成一覧には，商品カテゴリを集計種別として商品カテゴリ名（項目）ごとに集計したものと，メーカを集計種別としてメーカコード（項目）ごとに集計したものとの2種類がある。' +
      (saleCases[index].group === '商品カテゴリ'
        ? '集計種別を商品カテゴリ，すなわち集計する項目（以下，集計項目という）を商品カテゴリ名として集計したときの販売構成一覧の例を，図3に示す。'
        : '集計する項目（以下，集計項目という）をメーカコードとし，集計種別をメーカとして集計したときの販売構成一覧の例を，図3に示す。')),
    draw('saleReport', index, '図3　販売構成一覧の例'),
  ], [
    p('（4）利用者は，販売データの集計期間を指定する。指定した期間の販売データは必ず1件以上あるものとする。また，利用者は，集計種別として商品カテゴリ又はメーカのどちらかを指定する。'),
    p('（5）販売構成一覧の作成手順は，次のとおりである。'),
    p('① 集計期間の販売データを販売ファイルから抽出し，商品コードの昇順に並べ替える。'),
    p('② ①の結果の販売データ及び商品ファイルのレコードを，商品コードをキーとして突き合わせる。キーが一致した場合，商品ファイルのレコードと販売データのレコードから必要な項目の値を取り出して，それらを中間ファイルAに出力する。'),
    p('③ 中間ファイルAのレコードから，販売数と販売金額の値を取り出す。さらに，集計項目の値を取り出し，それら三つの値からなるレコードを中間ファイルBに出力する。'),
    p('④ 中間ファイルBのレコードを並べ替えて，集計項目ごとに販売数と販売金額を合計し，中間ファイルCに出力する。中間ファイルBの全レコードの販売金額を合計し，中間ファイルDに出力する。'),
    p('⑤ 集計項目ごとに合計した' + primary + 'の高い順に順位を付ける。'),
    p('⑥ 集計項目ごとに合計した販売金額の，すべての販売金額の合計に対する百分率を算出する。これを，販売構成一覧で表示する集計項目ごとの構成比率とする。'),
    p('⑦ 販売構成一覧の形式に合わせて作表する。'),
    p('（6）中間ファイルAと中間ファイルBのレコード様式を図4に示す。'),
    draw('interimRecords', 0, '図4　中間ファイルAと中間ファイルBのレコード様式'),
    p('（7）販売構成一覧の作成の流れを図5に示す。'),
  ], [
    draw('saleFlow', 0, '図5　販売構成一覧の作成の流れ'),
  ], [
    p('設問1　図5の“利用者指定値の読込み”で入力する項目として正しい答えを，解答群の中から選べ。'),
    ...bank('解答群', banks[0]),
    p('設問2　図5の“整列2”と“整列3”で行う並替えのキー項目として，図5中の［空欄］に入れる正しい答えを，解答群の中から選べ。'),
    ...bank('解答群', banks[1]),
    p('設問3　次の記述中の［空欄］に入れる正しい答えを，解答群の中から選べ。'),
    p('利用者が指定できる集計種別として' + newGroup + 'を追加し，' + field + '別販売構成一覧を作成する場合を考える。図5中の α 部分を図6に置き換えることで，既存の処理を変更せずに' +
      field + '別販売構成一覧が作成できる。図5の“抽出した販売データ”の項目には' + field + 'はあるが，中間ファイルAには' +
      field + 'がない。中間ファイルBの集計項目には，' + field + 'の値が必要である。そこで，集計種別が' + newGroup +
      'の場合に実行する処理として［c］を追加する。その実行条件は［d］である。'),
  ], [
    draw('saleExtension', 0, '図6　図5中の α 部分と置き換える部分'),
    ...bank('cに関する解答群', banks[2]), ...bank('dに関する解答群', banks[3]),
  ], [
    p('設問4　次の記述中の［空欄］に入れる正しい答えを，解答群の中から選べ。解答は，重複して選んでもよい。'),
    p('販売構成一覧の表示について，利用者から次の要求①〜③が発生した。'),
    p('① 順位が' + top + '位までのデータだけが表示されるようにする。'),
    p('② 構成比率で' + ratio + '％以上のデータだけが表示されるようにする。'),
    p('③ 順位が同じデータの場合，' + secondary + 'で降順に表示されるようにする。'),
    p('要求①〜③を最も効率よく満たす方法を考える。要求①に対しては，図5中の［e］の処理に，順位の値が' +
      top + '以下のレコードだけを出力する機能を追加すればよい。また，要求②に対しては，図5中の［f］の処理に，構成比率の値が' +
      ratio + '以上のレコードを出力する機能を追加すればよい。一方，要求③に対しては，第1キーを順位の昇順，第2キーを' + secondary +
      'の降順として，読み込んだレコードを並べ替えて出力する“整列4”を，新規の処理として，図5中の［g］の直前に追加すればよい。'),
    ...bank('解答群', banks[4]),
  ]];
}

