function variant(prompt: string, correctIndex: number, explanation: string, choices?: string[]): Variant {
  return { prompt, correctIndex, explanation, choices };
}

const byRole = (prompt: string, entries: readonly (readonly [string, number, string])[]) =>
  entries.map(([target, index, explanation]) => variant(prompt.replace("{target}", target), index, explanation));

