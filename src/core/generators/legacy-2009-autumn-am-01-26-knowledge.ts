import { define, source, textBody } from './legacy-2009-autumn-am-01-26-shared';

type Topic = readonly [string, string];

function descriptions(number: number, topics: readonly Topic[], original: number,
  ask: (name: string) => string, review: string) {
  const conditions = [original, ...topics.map((_, i) => i).filter(i => i !== original)];
  return define(number, '問いの対象', conditions.length, review, index => {
    const answer = conditions[index];
    const [name, explanation] = topics[answer];
    return textBody(index === 0 ? source[number].prompt : ask(name), source[number].choices, answer, explanation);
  });
}

