import type { Block } from '../types';
import { p, strings } from './definition';
import { answers, bank, define, single } from './legacy-2006-spring-pm-01-05-shared';
import { draw } from './legacy-2006-spring-pm-01-05-figures';
import { hashStrides } from './legacy-2006-spring-pm-01-05-models';

const allocate = (value: number) => value === 1 ? 'n' : value + '×n';
const options = ['hash', 'K', 'M', 'n', 'otp(M＋1)', 'otp(n)', '利用者ID'];

export function spring2006Pm2Pages(index: number, print = true): Block[][] {
  const stride = hashStrides[index], rounds = allocate(stride);
  return [
    [p('サーバへのログイン管理に関する次の記述を読んで，設問に答えよ。'),
      p('使い捨てパスワード（One-Time Password：OTP）の仕組みを応用して作られた，ログイン管理システムである。'),
      draw('otp-system', 0, 'ログイン管理システムの構成'),
      p('〔ログイン管理システムの説明〕'),
      p('サーバへのログイン可能回数Mと定数Kを決定し，M個の有効な使い捨てパスワードを使用する。残りのログイン可能回数がnのときの使い捨てパスワードotp(n)には，一方向性関数 hash を用いて，次式で得られる値を用いる。'),
      { type: 'formula', format: 'unicode',
        text: 'otp(n)＝hash(hash(…hash(K)…))　［hash を' + rounds + '回適用］',
        alt: 'otp(n)＝hash(hash(…hash(K)…))。hash をKから' + rounds + '回適用する。' },
      p('（1）使い捨てパスワード生成装置'),
      p('利用者が，使い捨てパスワードをすべて記憶し，管理することは困難なので，定数Kと残りのログイン可能回数nから使い捨てパスワードを生成し，表示する携帯式の使い捨てパスワード生成装置を用いる。'),
      p('第1回目のパスワード生成時はn＝Mで，パスワードを生成するたびにnを1ずつ減らし，最後のパスワード生成時は，n＝1となる。'),
      p('（2）利用者'),
      p('利用者は，Kを使い捨てパスワード生成装置に入力し，表示された使い捨てパスワードを，サーバへのログインパスワードとしてクライアントPCに入力する。'),
      p('（3）サーバ'), p('サーバは，次の二つを保持する。'),
      p('① 使い捨てパスワード生成装置と同じ一方向性関数 hash'),
      p('② パスワード検査に用いるために，利用者が直前の許可されたログインで使ったパスワード otp(n＋1)')],
    [p('サーバでのパスワード検査は，ログイン時にクライアントPCからサーバへ送られてきた使い捨てパスワード otp(n) に，hash を' + stride +
      '回適用し，' + (stride === 1 ? 'hash(otp(n))' : 'その結果') + 'を得て，それがサーバの保持している otp(n＋1) と一致するかどうかで行う。一致すれば，サーバは，ログインを許可する。'),
      p('サーバは，保持している otp(n＋1) を次回の検査用に更新する必要がある。このためには，クライアントPCから送られてきた使い捨てパスワードの値 otp(n) で置き換えればよい。'),
      p('図にログイン管理の流れを示す。ここでは，サーバには，利用者の otp(n) を受け入れる準備として，otp(n＋1) が保持されているものとする。また，この図では，時間は上から下に向かって進むように表現されている。'),
      draw('otp-flow', 0, '図　ログイン管理の流れ'),
      p('〔図中の主な処理の説明〕'),
      p('① 利用者IDによってサーバにログイン操作を行う。'),
      p('② パスワードを要求する。'),
      p('③ 使い捨てパスワード otp(n) をサーバへ送る。'),
      p('④ 受け取った otp(n) に hash を' + (stride === 1 ? '適用し，hash(otp(n))を得る。' : stride + '回適用する。') +
        '利用者IDごとに保存していた otp(n＋1) と比較する。一致すれば，ログインを許可し，受け取った otp(n) を次回のパスワード検査用に保持する。一致しなければ，ログインを拒否する。')],
    [p('設問　このログイン管理に関する次の記述中の空欄に入れる正しい答えを，解答群の中から選べ。'),
      p('利用者がパスワードとしてクライアントPCに入力する［a］は，ネットワーク上の通信メッセージにも含まれる。しかし，［a］は，ログイン許可と同時に無効なパスワードとなるので，これを盗聴してその後で使用しても，サーバにログインすることはできない。'),
      p('サーバが保持する使い捨てパスワード otp(n＋1) は，使用済みの無効なパスワードなので，これを不正に入手して使用しても，サーバにログインすることはできない。また，otp(n＋1) と hash を不正に入手したとしても，hash の一方向性の特徴から，これらを基に，未使用の使い捨てパスワードを得ることは極めて困難である。'),
      p('このログイン管理の仕組みで，不正アクセスの危険性が大きいのは，［b］と［c］の両方が不正に入手，使用された場合である。'),
      p('このうち，［b］は，サーバと使い捨てパスワード生成装置にある。サーバには，セキュリティ強化のための既存の手段を講じることができるが，使い捨てパスワード生成装置は，別の利用者も所有しているので，その不正使用及び盗難の危険性は比較的高い。'),
      p('［c］は，クライアントPC，ネットワーク上の通信メッセージ及びサーバには一時にも存在しない情報なので，これらから盗まれる危険はない。また，［c］は，利用者本人だけが知る秘密情報である。'),
      ...(print ? bank('解答群', options) : [])],
  ];
}

export const spring2006Pm2 = define(
  2, 'ハッシュ鎖による使い捨てパスワード', 'a=カ／b=ア／c=イ',
  '一つのパスワード生成段階当たりのハッシュ回数',
  'ハッシュ鎖で隣り合う使い捨てパスワード間の適用回数を変更し，生成式とサーバ側の検査手順を対応させる。',
  'ログイン装置、時間順の図2点（構成、流れ）、Mから1への単調減少、直前成功値の更新、一方向性、秘密の所在、7択3欄を保持。ハッシュ反復回数は1〜4。情報の役割と共有箇所は全条件で同じため選ぶ語は固定。作品や第三者製品の図版・仕様引用の表示なし。',
  index => ({
    prompt: spring2006Pm2Pages(index, false).flat(),
    ...answers([strings(options)], [single('a','a',0,5),single('b','b',0,0),single('c','c',0,1)]),
    explanation: 'OTP（One-Time Password、使い捨てパスワード）として送る値は otp(n)。サーバは届いた値に hash を'+hashStrides[index]+
      '回適用し，' + allocate(hashStrides[index]) + '回の適用で生成された今回値から，保持中の前回値へ進めることを確かめる。成功後は今回値を保持するので，使用済みの値をそのまま送っても再ログインできない。hash はサーバと生成装置で共有する一方向性関数。K は利用者本人だけが知り，クライアントPC、通信メッセージ、サーバに現れない。K と hash が分かると生成を再現できる。使い捨て値を競合なく利用できることを前提とした，この問題の方式についての説明である。',
  }), { answerVariation: 'fixed' },
);
