import { p } from './definition';
import { answers, bankAt, caseIndex, common, prompt, type Page } from './legacy-2009-spring-pm-05-08-shared';
import { drawing } from './legacy-2009-spring-pm-05-08-figures';

const fees=[
  {minimum:'10万円',before:false,perAccount:false,limits:''},
  {minimum:'12万円',before:true,perAccount:false,limits:''},
  {minimum:'判定下限額',before:false,perAccount:true,limits:'口座種別は標準口座と積立口座で，それぞれ判定下限額8万円と15万円を適用する。'},
  {minimum:'判定下限額',before:true,perAccount:true,limits:'口座種別は一般口座と特別口座で，それぞれ判定下限額5万円と20万円を適用する。'},
] as const;
const mark='その口座の手数料マークの値';
const balance='その口座の残高';
const order=['処理Dの次に処理E','処理Eの次に処理D','任意'];
export function feeBanks(index:number) {
  const {perAccount}=fees[index];
  const amount=perAccount?'その口座の口座管理手数料':'所定の口座管理手数料';
  return [
    ['処理A','処理B','データベースの検索','データベースの項目内容変更','データベースのレコード削除'],
    [amount,amount+'，'+balance,amount+'，'+balance+'，'+mark,perAccount?balance+'，その口座の口座種別':balance,mark],
    order,
  ];
}

export function feePages(index:number):readonly Page[] {
  const c=fees[index];
  const when=c.before?'前月末日の手数料引落し直前':'前月末日時点';
  const amount=c.perAccount?'口座ごとに定められた':'所定の';
  const next=c.before?'翌月手数料マーク':'手数料マーク';
  return [[18,[
    p('問5　銀行口座の管理に関する次の記述を読んで，設問に答えよ。'),
    p('ある銀行の個人顧客口座の口座管理手数料，現金自動預払機（以下，ATMという）での預払い及びATM使用手数料に関する口座情報を更新するプログラムである。'),
    p('口座は，口座番号で識別される。口座には，'+amount+'口座管理手数料が毎月掛かり，その月の月末処理で残高から引き落とされる。この口座管理手数料は，その口座の'+when+
      'の残高が'+c.minimum+'以上であれば，当月分は掛からない。'+c.limits),
    p('口座に対してのATMからの預入れ及び引出しの操作には，1回当たり所定のATM使用手数料が掛かり，操作時に，その口座の残高から自動的に引き落とされる。このATM使用手数料も，その口座の'+when+
      'の残高が'+c.minimum+'以上であれば，当月分は掛からない。'),
    p('なお，同一口座に対しては，預入れ及び引出しの操作が完了するまで，ほかの操作は行えないものとする。'),
    p('データベースには，'+amount+'口座管理手数料及び所定のATM使用手数料と，口座ごとの残高及び手数料マーク'+
      (c.perAccount?'，口座種別':'')+(c.before?'，翌月手数料マーク':'')+'が格納されている。'),
    p('手数料マークは，'+when+'の残高が'+c.minimum+'未満であった場合に“真”，そうでない場合に“偽”となる。'+
      (c.before?'月末処理では，手数料引落し前の残高を使って翌月手数料マークを設定する。引落し前の残高は別に保存しない。処理Dには，処理時点の残高をそのまま用いる。翌月手数料マークは当月分の手数料マークとは別に保持され，DとEの両方が終了してから翌月分に切り替わる。':'')),
    p('プログラムを構成する各モジュール間の関連を図に示す。'),drawing('5-modules',index),
  ]],[19,[
    p('〔預払トランザクション構成モジュールの説明〕'),
    p('このモジュールには，次の各処理が用意されており，口座ごとに，預払い1件を単位として一つのトランザクションを構成する。'),
    p('処理A：ATMでの預払操作に対応して，データベースを更新する命令を作成し，データベース更新モジュールに送る。'),
    p('処理B：残高不足となる場合は，利用者にメッセージで伝え，預払処理を行わない。'),
    p('処理C：データベースを更新する命令1件に対して，所定のATM使用手数料を口座から引き落とす命令を作成し，データベース更新モジュールに送る。'),
    p('〔データベース更新モジュールの説明〕'),
    p('到着した順番にトランザクションを処理し，データベース上の対応する口座の情報を更新する。'),
    p('〔月末処理モジュールの説明〕'),
    p('このモジュールには，次の各処理が用意されており，月末処理のため，口座ごとに一つのトランザクションを構成し，必要な処理を行う。月末処理は，月末日のATMからの操作受付終了後に行う。'),
    p('処理D：翌月のために'+next+'を設定する命令を作成し，データベース更新モジュールに送る。'),
    p('処理E：'+amount+'口座管理手数料を残高から引き落とした新たな残高を計算する。新たな残高を書き戻す命令を作成して，データベース更新モジュールに送る。計算結果の残高が負の値になることもある。'),
  ]],[20,[
    p('設問　次の各モジュールに関する記述中の空欄［a］～［f］に入れる正しい答えを，解答群の中から選べ。'),
    p('預払トランザクション構成モジュールでは，それぞれの実行条件に従って処理A～C及びデータベースへのアクセスが実行される。その順番は，次のとおりである。'),
    drawing('5-sequence',index),
    p('月末処理モジュールの処理Dでの'+next+'の設定に最低限必要なデータは，［d］である。また，処理Eは実行される場合とされない場合がある。処理Eの実行判定に必要なデータと，処理Eの実行に最低限必要なデータは，［e］である。'),
    p('ここで，月末処理モジュールの処理D，処理Eの両方が実行される場合，その順番は，［f］である。'),
    bankAt(0,'a～cに関する解答群'),bankAt(1,'d，eに関する解答群'),bankAt(2,'fに関する解答群'),
  ]]];
}

