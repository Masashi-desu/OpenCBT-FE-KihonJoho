import {
  type GenerationDefinition,
  field,
  p,
  strings,
  variableNotes,
} from "./definition";

type Item = [term: string, meaning: string];
type Mode = "description" | "term" | "action";
function knowledge(
  source: string,
  title: string,
  sourceAnswer: string,
  items: Item[],
  mode: Mode = "description",
): GenerationDefinition {
  return {
    source,
    title,
    sourceAnswer,
    fields: [
      field("問う対象", 0, items.length - 1),
      field("設問の方向と判定条件", 0, 2),
    ],
    reference: [0, 0],
    notes:
      variableNotes +
      " 知識問題は登録した正しい概念・条件の対応から問う対象を選ぶ。意味から名称／目的、名称／目的から意味、誤った対応の識別を切り替える。単なる選択肢順・固有名詞の変更だけを生成として扱わない。",
    build: ([target, wording]) => {
      const [term, meaning] = items[target];
      if (wording === 2) {
        const wrong = items[(target + 1) % items.length][1];
        return {
          prompt: [
            p(
              "次の名称・目的と説明・方法の対応のうち、誤っているものはどれか。",
            ),
          ],
          choices: strings(
            items.map(
              ([name, text], i) => `${name}：${i === target ? wrong : text}`,
            ),
          ),
          correctIndex: target,
          explanation: `${term}に対応するのは「${meaning}」。提示した「${wrong}」は${items[(target + 1) % items.length][0]}の説明である。その他の組合せは登録された正しい対応を示す。`,
        };
      }
      const effectiveMode =
        wording === 1 ? (mode === "term" ? "description" : "term") : mode;
      const prompt =
        effectiveMode === "term"
          ? `${meaning}。これに該当する${mode === "action" ? "目的" : "名称"}はどれか。`
          : effectiveMode === "action"
            ? `${term}という目的に最も直接対応する対策はどれか。`
            : [
                `${term}の説明として適切なものはどれか。`,
                `${term}に該当する記述はどれか。`,
                `${term}の特徴を正しく説明したものはどれか。`,
              ][wording];
      const choices = items.map((item) =>
        effectiveMode === "term" ? item[0] : item[1],
      );
      return {
        prompt: [p(prompt)],
        choices: strings(choices),
        correctIndex: target,
        explanation: `${term}は、${meaning}。${items
          .filter((_, i) => i !== target)
          .map(([t, m]) => `${t}は${m}`)
          .join("。")}。問う対象と選択肢の意味を対応させる。`,
      };
    },
  };
}
